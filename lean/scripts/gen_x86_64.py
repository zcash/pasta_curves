@dataclasses.dataclass(frozen=True)
class RoutineConfig:
    rust_name: str
    lean_name: str
    args: Tuple[Tuple[str, str], ...]
    result_type: str
    result_count: int
    doc: str


RESERVED_OPERAND_NAMES = {"rdx", "cf", "ofl", "s", "d", "m", "n"}


def validate_high_limb(source: str) -> None:
    matches = re.findall(
        r"^\s*const\s+PASTA_HIGH_LIMB\s*:\s*u64\s*=\s*([^;]+);",
        source,
        re.MULTILINE,
    )
    if len(matches) != 1:
        raise GenerationError("expected exactly one PASTA_HIGH_LIMB declaration")
    expression = re.sub(r"\s+", "", matches[0])
    if expression != "1<<62" or PASTA_HIGH_LIMB != 0x4000000000000000:
        raise GenerationError(
            "PASTA_HIGH_LIMB must be `1 << 62` (0x4000000000000000)"
        )


def parse_declaration(text: str) -> Declaration:
    return asm_source.parse_declaration(
        text,
        reserved_names=RESERVED_OPERAND_NAMES,
        fixed_registers={"rdx"},
        const_operands={"PASTA_HIGH_LIMB"},
    )


