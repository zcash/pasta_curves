def _rename_from_mont(value, renaming):
    """Rename physical registers in one macro-expanded binding IR value."""
    if isinstance(value, str):
        for register in sorted(renaming, key=len, reverse=True):
            value = re.sub(
                rf"(?<![A-Za-z0-9_']){re.escape(register)}(?![A-Za-z0-9_'])",
                renaming[register],
                value,
            )
        return value
    if isinstance(value, tuple):
        return tuple(_rename_from_mont(item, renaming) for item in value)
    if isinstance(value, list):
        return [_rename_from_mont(item, renaming) for item in value]
    return value


def _from_mont_fingerprint(entries):
    """Semantic IR fields whose equality permits factoring a flattened round."""
    return [
        (
            entry["name"],
            entry["expr"],
            tuple(sorted(entry["reads"])),
            entry["load"],
            entry["fact"],
            entry["pc"],
        )
        for entry in entries
    ]


def _normalized_from_mont_round(emitter, first_pc, registers):
    """Canonicalize one 21-instruction round under its source register rotation."""
    renaming = dict(zip(registers, (*FROM_MONT_STATE_FIELDS, "tmp")))
    entries = []
    for entry in emitter.entries:
        if entry["pc"] is None or not first_pc <= entry["pc"] < first_pc + 21:
            continue
        normalized = dict(entry)
        for key in ("name", "expr", "fact"):
            normalized[key] = _rename_from_mont(entry[key], renaming)
        normalized["reads"] = {_rename_from_mont(read, renaming) for read in entry["reads"]}
        normalized["pc"] = entry["pc"] - first_pc
        entries.append(normalized)
    return entries


def _check_from_mont_helper_accounting(round_entries, prefix_entries, suffix_entries):
    """Require the prefix and suffix to cover and reconstruct one normalized source round."""
    prefix_pcs = sorted({entry["pc"] for entry in prefix_entries})
    suffix_pcs = sorted({entry["pc"] for entry in suffix_entries})
    if prefix_pcs != list(range(3)):
        raise GenerationError("from_mont: quotient prefix does not cover PCs 0 through 2")
    if suffix_pcs != list(range(3, 21)):
        raise GenerationError("from_mont: sparse suffix does not cover PCs 3 through 20")
    if _from_mont_fingerprint(prefix_entries + suffix_entries) != _from_mont_fingerprint(
        round_entries
    ):
        raise GenerationError("from_mont: factored helpers do not reconstruct the normalized round")


def _check_from_mont_prefix_accounting(
    prefix_entries, quotient_entries, self_sub_entries, mask_entries
):
    """Require the three one-instruction helpers to reconstruct the exact prefix IR."""
    if sorted({entry["pc"] for entry in quotient_entries}) != [0]:
        raise GenerationError("from_mont: quotient helper does not cover PC 0")
    if sorted({entry["pc"] for entry in self_sub_entries}) != [1]:
        raise GenerationError("from_mont: self-subtraction helper does not cover PC 1")
    if sorted({entry["pc"] for entry in mask_entries}) != [2]:
        raise GenerationError("from_mont: mask helper does not cover PC 2")
    if _from_mont_fingerprint(
        quotient_entries + self_sub_entries + mask_entries
    ) != _from_mont_fingerprint(prefix_entries):
        raise GenerationError("from_mont: short prefix helpers do not reconstruct PCs 0 through 2")


def _check_from_mont_final_reduction_accounting(
    final_entries, subtraction_entries, addback_entries
):
    """Require the two final-reduction helpers to reconstruct the exact normalized suffix."""
    if sorted({entry["pc"] for entry in subtraction_entries}) != list(range(14)):
        raise GenerationError("from_mont: final subtraction helper does not cover PCs 0 through 13")
    if sorted({entry["pc"] for entry in addback_entries}) != list(range(14, 31)):
        raise GenerationError("from_mont: final add-back helper does not cover PCs 14 through 30")
    if _from_mont_fingerprint(subtraction_entries + addback_entries) != _from_mont_fingerprint(
        final_entries
    ):
        raise GenerationError(
            "from_mont: final reduction helpers do not reconstruct PCs 0 through 30"
        )


def _normalized_from_mont_final_reduction(emitter):
    """Canonicalize the checked 31-instruction suffix under its post-round register mapping."""
    first_pc, end_pc = 177, 208
    renaming = dict(zip(FROM_MONT_FINAL_REGISTERS, FROM_MONT_STATE_FIELDS))
    entries = []
    for entry in emitter.entries:
        if entry["pc"] is None or not first_pc <= entry["pc"] < end_pc:
            continue
        normalized = dict(entry)
        for key in ("name", "expr", "fact"):
            normalized[key] = _rename_from_mont(entry[key], renaming)
        normalized["reads"] = {_rename_from_mont(read, renaming) for read in entry["reads"]}
        normalized["pc"] = entry["pc"] - first_pc
        entries.append(normalized)
    if sorted({entry["pc"] for entry in entries}) != list(range(end_pc - first_pc)):
        raise GenerationError("from_mont: final reduction does not cover PCs 177 through 207")
    return entries


def emit_from_mont_routines(source: str) -> list[Routine]:
    """Transcribe and mechanically factor the fixed-register conversion block."""
    parsed = parse_from_mont(source)
    declarations = tuple(
        (declaration.name, declaration.kind, declaration.value, declaration.output)
        for declaration in parsed.declarations
    )
    expected_declarations = (
        ("r0", "inout", "value.as_ptr()", "word1"),
        ("r1", "in", "modulus.as_ptr()", None),
        ("r2", "out", "word2", "word2"),
        ("r3", "out", "word3", "word3"),
        ("r4", "out", "word4", "word4"),
        ("r5", "out", "word5", "word5"),
        ("r8", "out", "word6", "word6"),
        ("r9", "out", "word7", "word7"),
        ("r10", "out", "_", None),
        ("r11", "out", "_", None),
        ("r12", "out", "_", None),
        ("r14", "out", "word0", "word0"),
    )
    if declarations != expected_declarations:
        raise GenerationError("from_mont: fixed-register declarations differ")
    returned = asm_source.returned_registers(parsed, "from_mont")
    expected_returned = ("r14", "r0", "r2", "r3", "r4", "r5", "r8", "r9")
    if returned != expected_returned:
        raise GenerationError(
            f"from_mont: returned registers differ: expected {expected_returned}, found {returned}"
        )

    directions = asm_source.declaration_directions(parsed, "from_mont")
    flat = Emitter(directions, {"r0": "value", "r1": "modulus"})
    flat.bind_pointer("r0", "value")
    flat.bind_pointer("r1", "modulus")
    for pc, instruction in enumerate(parsed.instructions):
        flat.pc = pc
        flat.emit_instruction(instruction)
    expected_value_offsets = list(range(0, 32, 4))
    expected_modulus_offsets = [4, 8, 12] * 10
    if flat.used_offsets["r0"] != expected_value_offsets:
        raise GenerationError(
            f"from_mont: value memory offsets differ: expected {expected_value_offsets}, "
            f"found {flat.used_offsets['r0']}"
        )
    if flat.used_offsets["r1"] != expected_modulus_offsets:
        raise GenerationError(
            f"from_mont: modulus memory offsets differ: expected {expected_modulus_offsets}, "
            f"found {flat.used_offsets['r1']}"
        )
    expected_final = (
        "subs.w lr, lr, #1",
        "ldr.w r11, [r1, #4]",
        "sbcs.w r0, r0, r11",
        "ldr.w r11, [r1, #8]",
        "sbcs.w r2, r2, r11",
        "ldr.w r11, [r1, #12]",
        "sbcs.w r3, r3, r11",
        "mov.w r11, #0",
        "sbcs.w r4, r4, r11",
        "sbcs.w r5, r5, r11",
        "sbcs.w r8, r8, r11",
        "mov.w r11, #0x40000000",
        "sbcs.w r9, r9, r11",
        "sbc.w r12, r10, r10",
        "and.w r11, r12, #1",
        "adds.w lr, lr, r11",
        "ldr.w r11, [r1, #4]",
        "and.w r11, r11, r12",
        "adcs.w r0, r0, r11",
        "ldr.w r11, [r1, #8]",
        "and.w r11, r11, r12",
        "adcs.w r2, r2, r11",
        "ldr.w r11, [r1, #12]",
        "and.w r11, r11, r12",
        "adcs.w r3, r3, r11",
        "mov.w r11, #0",
        "adcs.w r4, r4, r11",
        "adcs.w r5, r5, r11",
        "adcs.w r8, r8, r11",
        "and.w r11, r12, #0x40000000",
        "adc.w r9, r9, r11",
    )
    if parsed.instructions[177:] != expected_final:
        raise GenerationError("from_mont: final borrow selection differs")

    ring = list(FROM_MONT_ACCUMULATOR) + ["r0"]
    normalized_rounds = []
    rotations = []
    for site in range(8):
        registers = ring[site:] + ring[:site]
        rotations.append(registers)
        expected_arm = ", ".join("lr" if register == "r14" else register for register in registers)
        start = 9 + 21 * site
        origins = parsed.origins[start : start + 21]
        if len(origins) != 21 or any(
            origin is None
            or origin.macro != "from_mont_round"
            or origin.site != site
            or origin.arm != expected_arm
            for origin in origins
        ):
            raise GenerationError(
                f"from_mont: macro call {site + 1} does not use the expected register rotation"
            )
        normalized_rounds.append(_normalized_from_mont_round(flat, start, registers))
    if parsed.origins[:9] != (None,) * 9 or parsed.origins[177:] != (None,) * 31:
        raise GenerationError(
            "from_mont: instructions outside the eight macro calls changed origin"
        )
    fingerprint = _from_mont_fingerprint(normalized_rounds[0])
    if not fingerprint or any(
        _from_mont_fingerprint(round_entries) != fingerprint
        for round_entries in normalized_rounds[1:]
    ):
        raise GenerationError("from_mont: macro rounds differ after the exact register rotation")
    if tuple(rotations[-1][1:]) != FROM_MONT_FINAL_REGISTERS:
        raise GenerationError("from_mont: post-round-8 register mapping differs")

    state_directions = {field: "inout" for field in FROM_MONT_STATE_FIELDS}
    state_fields = {"st": list(FROM_MONT_STATE_FIELDS)}

    # Split each checked round at the source's first modulus load. PCs 0 through 2 compute the
    # Montgomery quotient and low-word cancellation carry; PCs 3 through 20 consume precisely
    # those two words in the sparse multiply/carry chain. Require both parts together to be the
    # normalized source round exactly, so no source instruction can disappear between them.
    round_entries = normalized_rounds[0]
    prefix_entries = [dict(entry) for entry in round_entries if entry["pc"] < 3]
    suffix_entries = [dict(entry) for entry in round_entries if entry["pc"] >= 3]
    _check_from_mont_helper_accounting(round_entries, prefix_entries, suffix_entries)

    # A record result makes Lean's let extraction for all three prefix instructions consume excessive
    # memory. Factor the exact checked prefix once more into one-instruction helpers, and require their
    # fingerprints to reconstruct PCs 0 through 2 before composing the record.
    quotient_entries = [dict(entry) for entry in prefix_entries if entry["pc"] == 0]
    self_sub_entries = [dict(entry) for entry in prefix_entries if entry["pc"] == 1]
    mask_entries = [dict(entry) for entry in prefix_entries if entry["pc"] == 2]
    _check_from_mont_prefix_accounting(
        prefix_entries, quotient_entries, self_sub_entries, mask_entries
    )

    quotient_emitter = Emitter({"w0": "inout"}, clear_values=False)
    quotient_emitter.bind("w0", "w0", "low accumulator word", reads=(), fact=("param", "w0"))
    quotient_emitter.entries.extend(quotient_entries)
    quotient_result = ["w0", "c"]
    quotient_routine = Routine(
        "The first instruction of one checked `from_mont_round!` invocation: compute the Montgomery "
        "quotient and the subtraction carry used by the next instruction.",
        "def fromMontRoundPrefixQuotient (w0 : Nat) : Nat × Nat :=",
        quotient_emitter.render(quotient_result),
        f"  ({', '.join(quotient_result)})",
        "fromMontRoundPrefixQuotient",
        quotient_emitter,
        quotient_result,
        struct=f"{FROM_MONT_STATE_STRUCT}\n\n{FROM_MONT_PREFIX_STRUCT}",
        lift_lets=False,
    )

    self_sub_emitter = Emitter({"w0": "in", "c": "in", "r12": "out"}, clear_values=False)
    self_sub_emitter.bind(
        "w0", "quotient", "Montgomery quotient", reads=(), fact=("param", "quotient")
    )
    self_sub_emitter.bind(
        "c", "subCarry", "subtraction carry", reads=(), fact=("param", "subCarry")
    )
    self_sub_emitter.entries.extend(self_sub_entries)
    self_sub_result = ["r12"]
    self_sub_routine = Routine(
        "The second instruction of one checked `from_mont_round!` invocation: self-subtract the "
        "quotient under the first instruction's carry.",
        "def fromMontRoundPrefixSelfSub (quotient subCarry : Nat) : Nat :=",
        self_sub_emitter.render(self_sub_result),
        "  r12",
        "fromMontRoundPrefixSelfSub",
        self_sub_emitter,
        self_sub_result,
        lift_lets=False,
    )

    mask_emitter = Emitter({"r12": "inout"}, clear_values=False)
    mask_emitter.bind(
        "r12", "selfSub", "self-subtraction result", reads=(), fact=("param", "selfSub")
    )
    mask_emitter.entries.extend(mask_entries)
    mask_result = ["r12"]
    mask_routine = Routine(
        "The third instruction of one checked `from_mont_round!` invocation: mask the "
        "self-subtraction result to the low-word cancellation carry.",
        "def fromMontRoundPrefixMask (selfSub : Nat) : Nat :=",
        mask_emitter.render(mask_result),
        "  r12",
        "fromMontRoundPrefixMask",
        mask_emitter,
        mask_result,
        lift_lets=False,
    )

    prefix_emitter = Emitter({})
    prefix_emitter.bind(
        "quotientResult",
        "fromMontRoundPrefixQuotient w0",
        "mechanically factored PC 0",
        reads={"w0"},
        fact=("call", "fromMontRoundPrefixQuotient {}", ["w0"]),
    )
    prefix_emitter.bind(
        "quotient",
        "quotientResult.1",
        "quotient helper output",
        reads={"quotientResult"},
        fact=("callout", "quotientResult", "1"),
    )
    prefix_emitter.bind(
        "subCarry",
        "quotientResult.2",
        "quotient helper output",
        reads={"quotientResult"},
        fact=("callout", "quotientResult", "2"),
    )
    prefix_emitter.bind(
        "selfSub",
        "fromMontRoundPrefixSelfSub quotient subCarry",
        "mechanically factored PC 1",
        reads={"quotient", "subCarry"},
        fact=("call", "fromMontRoundPrefixSelfSub {} {}", ["quotient", "subCarry"]),
    )
    prefix_emitter.bind(
        "carry",
        "fromMontRoundPrefixMask selfSub",
        "mechanically factored PC 2",
        reads={"selfSub"},
        fact=("call", "fromMontRoundPrefixMask {}", ["selfSub"]),
    )
    prefix_result = ["quotient", "carry"]
    prefix_routine = Routine(
        "The first three instructions of one checked `from_mont_round!` invocation, composed from "
        "three mechanically accounted one-instruction helpers: compute the quotient and the carry "
        "that cancels the low accumulator word.",
        "def fromMontRoundPrefix (w0 : Nat) : FromMontRoundPrefix :=",
        prefix_emitter.render(prefix_result),
        f"  ⟨{', '.join(prefix_result)}⟩",
        "fromMontRoundPrefix",
        prefix_emitter,
        prefix_result,
        lift_lets=False,
    )

    suffix_directions = dict(state_directions)
    suffix_directions.update({"tmp": "out", "r12": "inout", "r1": "in"})
    suffix_emitter = Emitter(suffix_directions, {"r1": "modulus"})
    suffix_emitter.bind_pointer("r1", "modulus")
    for field in FROM_MONT_STATE_FIELDS[1:]:
        suffix_emitter.bind(
            field,
            f"st.{field}",
            "accumulator argument",
            reads=(),
            load=True,
            fact=("word_state_load", "st", field, gen.proj("st", field, state_fields)),
        )
    suffix_emitter.bind("w0", "q", "Montgomery quotient", reads=(), fact=("param", "q"))
    suffix_emitter.bind(
        "r12", "carry", "low-word cancellation carry", reads=(), fact=("param", "carry")
    )
    suffix_emitter.entries.extend(suffix_entries)
    suffix_result = [*FROM_MONT_STATE_FIELDS[1:], "tmp"]
    suffix_routine = Routine(
        "The final eighteen instructions of one checked `from_mont_round!` invocation: multiply "
        "the sparse modulus by the quotient and propagate its carry through the accumulator.",
        "def fromMontRoundSuffix (modulus : Limbs) (st : FromMontState) "
        "(q carry : Nat) : FromMontState :=",
        suffix_emitter.render(suffix_result),
        f"  ⟨{', '.join(suffix_result)}⟩",
        "fromMontRoundSuffix",
        suffix_emitter,
        suffix_result,
        arg_fields=state_fields,
    )

    round_emitter = Emitter({})
    round_emitter.bind(
        "quotientResult",
        "fromMontRoundPrefix st.w0",
        "mechanically factored PCs 0 through 2",
        reads={"st"},
        fact=("call", "fromMontRoundPrefix {}", ["st.w0"]),
    )
    round_emitter.bind(
        "q",
        "quotientResult.quotient",
        "quotient prefix output",
        reads={"quotientResult"},
        fact=("callout", "quotientResult", "quotient"),
    )
    round_emitter.bind(
        "carry",
        "quotientResult.carry",
        "quotient prefix output",
        reads={"quotientResult"},
        fact=("callout", "quotientResult", "carry"),
    )
    round_emitter.bind(
        "suffix",
        "fromMontRoundSuffix modulus st q carry",
        "mechanically factored PCs 3 through 20",
        reads={"modulus", "st", "q", "carry"},
        fact=("call", "fromMontRoundSuffix {} {} {} {}", ["modulus", "st", "q", "carry"]),
    )
    for field in FROM_MONT_STATE_FIELDS:
        round_emitter.bind(
            field,
            f"suffix.{field}",
            "sparse suffix output",
            reads={"suffix"},
            fact=("callout", "suffix", field),
        )
    round_result = list(FROM_MONT_STATE_FIELDS)
    round_routine = Routine(
        "One `from_mont_round!` invocation, composed from the mechanically checked quotient prefix "
        "and sparse multiply/carry suffix. All eight invocations are required to have the same "
        "binding IR after applying their exact source register rotation.",
        "def fromMontRound (modulus : Limbs) (st : FromMontState) : FromMontState :=",
        round_emitter.render(round_result),
        f"  ⟨{', '.join(round_result)}⟩",
        "fromMontRound",
        round_emitter,
        round_result,
        arg_fields=state_fields,
    )

    final_entries = _normalized_from_mont_final_reduction(flat)
    final_subtraction_entries = [dict(entry) for entry in final_entries if entry["pc"] < 14]
    final_addback_entries = [dict(entry) for entry in final_entries if entry["pc"] >= 14]
    _check_from_mont_final_reduction_accounting(
        final_entries, final_subtraction_entries, final_addback_entries
    )

    final_subtraction_directions = dict(state_directions)
    final_subtraction_directions.update({"r1": "in"})
    final_subtraction_emitter = Emitter(final_subtraction_directions, {"r1": "modulus"})
    final_subtraction_emitter.bind_pointer("r1", "modulus")
    for field in FROM_MONT_STATE_FIELDS:
        final_subtraction_emitter.bind(
            field,
            f"st.{field}",
            "post-round accumulator argument",
            reads=(),
            load=True,
            fact=("word_state_load", "st", field, gen.proj("st", field, state_fields)),
        )
    final_subtraction_emitter.entries.extend(final_subtraction_entries)
    final_subtraction_result = [*FROM_MONT_STATE_FIELDS, "c", "r12"]
    final_subtraction_routine = Routine(
        "The first fourteen instructions of the checked `from_mont` final reduction: subtract "
        "the sparse modulus and turn the final no-borrow carry into an add-back mask.",
        "def fromMontFinalSubtractionBlock (modulus : Limbs) (st : FromMontState) "
        ": FromMontFinalSubtraction :=",
        final_subtraction_emitter.render(final_subtraction_result),
        f"  ⟨{', '.join(final_subtraction_result)}⟩",
        "fromMontFinalSubtractionBlock",
        final_subtraction_emitter,
        final_subtraction_result,
        struct=FROM_MONT_FINAL_SUBTRACTION_STRUCT,
        arg_fields=state_fields,
    )

    final_subtraction_fields = [*FROM_MONT_STATE_FIELDS, "carry", "mask"]
    final_addback_directions = dict(state_directions)
    final_addback_directions.update({"r1": "in", "r12": "in"})
    final_addback_emitter = Emitter(final_addback_directions, {"r1": "modulus"})
    final_addback_emitter.bind_pointer("r1", "modulus")
    for field in FROM_MONT_STATE_FIELDS:
        final_addback_emitter.bind(
            field,
            f"sub.{field}",
            "subtraction helper output",
            reads=(),
            load=True,
            fact=(
                "word_state_load",
                "sub",
                field,
                gen.proj("sub", field, {"sub": final_subtraction_fields}),
            ),
        )
    final_addback_emitter.bind(
        "r12",
        "sub.mask",
        "subtraction borrow mask",
        reads=(),
        fact=(
            "word_state_load",
            "sub",
            "mask",
            gen.proj("sub", "mask", {"sub": final_subtraction_fields}),
        ),
    )
    final_addback_emitter.entries.extend(final_addback_entries)
    final_addback_result = list(FROM_MONT_STATE_FIELDS)
    final_addback_routine = Routine(
        "The final seventeen instructions of the checked `from_mont` final reduction: add the "
        "sparse modulus back under the subtraction helper's borrow mask.",
        "def fromMontFinalAddBackBlock (modulus : Limbs) (sub : FromMontFinalSubtraction) "
        ": FromMontState :=",
        final_addback_emitter.render(final_addback_result),
        f"  ⟨{', '.join(final_addback_result)}⟩",
        "fromMontFinalAddBackBlock",
        final_addback_emitter,
        final_addback_result,
        arg_fields={"sub": final_subtraction_fields},
    )

    final_emitter = Emitter({})
    final_emitter.bind(
        "subtraction",
        "fromMontFinalSubtractionBlock modulus st",
        "mechanically factored PCs 0 through 13",
        reads={"modulus", "st"},
        fact=("call", "fromMontFinalSubtractionBlock {} {}", ["modulus", "st"]),
    )
    final_emitter.bind(
        "addback",
        "fromMontFinalAddBackBlock modulus subtraction",
        "mechanically factored PCs 14 through 30",
        reads={"modulus", "subtraction"},
        fact=("call", "fromMontFinalAddBackBlock {} {}", ["modulus", "subtraction"]),
    )
    final_routine = Routine(
        "The checked 31-instruction suffix of `from_mont`, composed from mechanically accounted "
        "subtraction-mask and masked-add-back helpers. Its ninth accumulator word is unchanged.",
        "def fromMontFinalReductionBlock (modulus : Limbs) (st : FromMontState) : FromMontState :=",
        final_emitter.render(["addback"]),
        "  addback",
        "fromMontFinalReductionBlock",
        final_emitter,
        ["addback"],
        arg_fields=state_fields,
    )

    main_emitter = Emitter(directions, {"r0": "value", "r1": "modulus"})
    main_emitter.entries = [
        dict(entry) for entry in flat.entries if entry["pc"] is None or entry["pc"] < 9
    ]
    for site, registers in enumerate(rotations, 1):
        state_registers = registers[:9]
        fmt = "fromMontRound modulus ⟨" + ", ".join(f"{{{index}}}" for index in range(9)) + "⟩"
        call_name = f"round{site}"
        main_emitter.entries.append(
            {
                "name": call_name,
                "expr": fmt.format(*state_registers),
                "comment": f"from_mont_round!, invocation {site}",
                "note": None,
                "reads": {"modulus", *state_registers},
                "load": False,
                "fact": ("call", fmt, state_registers),
                "pc": None,
            }
        )
        for register, field in zip(registers[1:], FROM_MONT_STATE_FIELDS):
            main_emitter.entries.append(
                {
                    "name": register,
                    "expr": f"{call_name}.{field}",
                    "comment": f"round {site} output",
                    "note": None,
                    "reads": {call_name},
                    "load": False,
                    "optional": True,
                    "fact": ("callout", call_name, field),
                    "pc": None,
                }
            )
    final_fmt = (
        "fromMontFinalReductionBlock modulus ⟨"
        + ", ".join(f"{{{index}}}" for index in range(9))
        + "⟩"
    )
    final_call = "finalReduction"
    main_emitter.entries.append(
        {
            "name": final_call,
            "expr": final_fmt.format(*FROM_MONT_FINAL_REGISTERS),
            "comment": "checked final reduction, PCs 177 through 207",
            "note": None,
            "reads": {"modulus", *FROM_MONT_FINAL_REGISTERS},
            "load": False,
            "fact": ("call", final_fmt, FROM_MONT_FINAL_REGISTERS),
            "pc": None,
        }
    )
    for register, field in zip(FROM_MONT_FINAL_REGISTERS, FROM_MONT_STATE_FIELDS):
        main_emitter.entries.append(
            {
                "name": register,
                "expr": f"{final_call}.{field}",
                "comment": "final reduction output",
                "note": None,
                "reads": {final_call},
                "load": False,
                "optional": True,
                "fact": ("callout", final_call, field),
                "pc": None,
            }
        )
    result_names = []
    for limb, (low, high) in enumerate(zip(returned[::2], returned[1::2])):
        result = f"result{limb}"
        main_emitter.emit(
            result,
            f"{low} + wordMod * {high}",
            "join returned words",
            reads=(low, high),
            fact=("combine32", low, high),
        )
        result_names.append(result)
    main_routine = Routine(
        "The fixed-register inline `asm!` block of `from_mont`: load eight input words, apply "
        "eight mechanically checked rotated Montgomery rounds, then call the checked final "
        "reduction block once.",
        "def fromMontBlock (value modulus : Limbs) : Limbs :=",
        main_emitter.render(result_names),
        f"  ⟨{', '.join(result_names)}⟩",
        "fromMontBlock",
        main_emitter,
        result_names,
    )
    return [
        quotient_routine,
        self_sub_routine,
        mask_routine,
        prefix_routine,
        suffix_routine,
        round_routine,
        final_subtraction_routine,
        final_addback_routine,
        final_routine,
        main_routine,
    ]


BATCH_FINISH_STRUCT = """/-- Inputs and outputs of the mechanically factored final five instructions of a batch round. -/
structure BatchRoundFinish where
  pglo : Nat
  pghi : Nat
  remaining : Nat
  c : Nat
  z : Nat
  branch : Nat
  deriving DecidableEq, Repr"""


BATCH_STATE_STRUCT = """/-- The registers and public loop control carried by one `batch` round. -/
structure BatchState where
  /-- The low word of packed `f`. -/
  pflo : Nat
  /-- The high word of packed `f`. -/
  pfhi : Nat
  /-- The low word of packed `g`. -/
  pglo : Nat
  /-- The high word of packed `g`. -/
  pghi : Nat
  /-- `two_delta`, in its low 32-bit register. -/
  d : Nat
  /-- The public number of rounds still to execute. -/
  remaining : Nat
  /-- The carry flag left by the decrement. -/
  c : Nat
  /-- The zero flag left by the decrement. -/
  z : Nat
  /-- Whether the source's backward branch is taken. -/
  branch : Nat
  deriving DecidableEq, Repr"""


BATCH_DECLARATIONS = (
    asm_source.Declaration("pflo", "inout", "pflo", "pflo"),
    asm_source.Declaration("pfhi", "inout", "pfhi", "pfhi"),
    asm_source.Declaration("pglo", "inout", "pglo", "pglo"),
    asm_source.Declaration("pghi", "inout", "pghi", "pghi"),
    asm_source.Declaration("d", "inout", "d", "d"),
    asm_source.Declaration("remaining", "inout", "remaining", "_"),
    asm_source.Declaration("odd", "out", "_", "_"),
    asm_source.Declaration("swap", "out", "_", "_"),
    asm_source.Declaration("alo", "out", "_", "_"),
    asm_source.Declaration("ahi", "out", "_", "_"),
    asm_source.Declaration("tmp", "out", "_", "_"),
)


def _composition_routine(doc, signature, name, bindings, result, result_names):
    """Build a generated routine for checked Rust outside an `asm!` block."""
    emitter = gen.Emitter()
    for binding, expression, comment, reads in bindings:
        emitter.bind(
            binding,
            expression,
            comment,
            reads=reads,
            fact=("composition", expression),
        )
    return Routine(
        doc,
        signature,
        emitter.render(result_names),
        result,
        name,
        emitter,
        result_names,
    )


def emit_batch_routines(source: str) -> list[Routine]:
    """Validate `batch`, transcribe its loop body once, and iterate it by public `k`."""
    asm_inner = _validate_exact_function(source, "batch", BATCH_RUST)
    instructions, origins, declarations, options = asm_source.parse_asm_invocation(
        source,
        asm_inner,
        "batch",
        reserved_names={"c", "m", "s"},
        allowed_options={"pure", "nomem", "nostack"},
        required_options={"pure", "nomem", "nostack"},
    )
    if origins != (None,) * len(instructions):
        raise GenerationError("batch: macro invocations in the loop body are unsupported")
    if declarations != BATCH_DECLARATIONS:
        raise GenerationError("batch: assembly operand declarations differ from the checked loop")
    if options != {"pure", "nomem", "nostack"}:
        raise GenerationError("batch: assembly options differ from the checked loop")
    if instructions[0] != "2:" or instructions[-1] != "bne 2b":
        raise GenerationError("batch: expected one loop from label `2:` through `bne 2b`")

    directions = {declaration.name: declaration.kind for declaration in declarations}
    emitter = Emitter(directions, loop_control=True, clear_values=False)
    carried = ("pflo", "pfhi", "pglo", "pghi", "d", "remaining")
    for register in carried:
        emitter.bind_argument(register, f"st.{register}")
    for pc, instruction in enumerate(instructions):
        emitter.pc = pc
        emitter.emit_instruction(instruction)
    if not emitter.loop_label_seen or not emitter.branch_seen:
        raise GenerationError("batch: loop label and backward branch must both be present")

    # Factor the last five instructions from the validated flat IR. This keeps Lean from recursively
    # normalizing the whole round's dependent let tail when its proof extracts the cross-word shift.
    split = next((i for i, entry in enumerate(emitter.entries) if entry["pc"] == 27), None)
    if split is None or [entry["pc"] for entry in emitter.entries[split:]] != [
        27,
        28,
        29,
        30,
        30,
        30,
        30,
        31,
    ]:
        raise GenerationError("batch: final shift and loop-control schedule changed")
    prefix_entries = emitter.entries[:split]
    suffix_entries = emitter.entries[split:]

    finish_emitter = Emitter(
        {"pglo": "inout", "pghi": "inout", "remaining": "inout"},
        loop_control=True,
        clear_values=False,
    )
    for register in ("pglo", "pghi", "remaining"):
        finish_emitter.bind_argument(register, register)
    finish_emitter.entries.extend(dict(entry) for entry in suffix_entries)
    finish_results = ["pglo", "pghi", "remaining", "c", "z", "branch"]
    finish_routine = Routine(
        "The final five instructions of one validated `batch` loop iteration: shift packed `g`, "
        "decrement the public count, and compute the backward-branch decision.",
        "def batchRoundFinish (pglo pghi remaining : Nat) : BatchRoundFinish :=",
        finish_emitter.render(finish_results),
        f"  ⟨{', '.join(finish_results)}⟩",
        "batchRoundFinish",
        finish_emitter,
        finish_results,
        struct=BATCH_FINISH_STRUCT,
        arg_fields={},
    )

    emitter.entries = prefix_entries
    emitter.bind(
        "finish",
        "batchRoundFinish pglo pghi remaining",
        "mechanically factored PCs 27 through 31",
        reads={"pglo", "pghi", "remaining"},
        fact=("call", "batchRoundFinish {} {} {}", ["pglo", "pghi", "remaining"]),
    )
    for field in finish_results:
        emitter.bind(
            field,
            f"finish.{field}",
            "factored suffix output",
            reads={"finish"},
            fact=("callout", "finish", field),
        )
    round_results = [*carried, "c", "z", "branch"]
    round_routine = Routine(
        "One complete iteration of the inline `asm!` loop of `batch`, including its public-count "
        "decrement, resulting flags, and backward-branch decision.",
        "def batchRound (st : BatchState) : BatchState :=",
        emitter.render(round_results),
        f"  ⟨{', '.join(round_results)}⟩",
        "batchRound",
        emitter,
        round_results,
        struct=BATCH_STATE_STRUCT,
        arg_fields={"st": list(carried)},
        # Extract the loop's lets one instruction at a time. Lifting the entire chain here makes
        # Lean recursively normalize the nested `BatchState` equality before `word_step` can
        # factor it, exhausting `maxRecDepth` even at impractically large settings.
        lift_lets=False,
    )

    batch_routine = _composition_routine(
        "The inline `asm!` block and surrounding Rust of `batch`: pack the low words, iterate the "
        "mechanically transcribed loop body by its public positive count `k`, sign-extend the new "
        "`two_delta`, and decode the two packed matrix rows.",
        "def batchBlock (k delta f g : Nat) : Divstep59Result :=",
        "batchBlock",
        [
            ("pf", "orrw (andw f 0xfffff) 0xfffffe0000000000", "pack the low word of f", {"f"}),
            ("pg", "orrw (andw g 0xfffff) 0xc000000000000000", "pack the low word of g", {"g"}),
            ("pflo", "pf % wordMod", "Rust cast to the low u32", {"pf"}),
            ("pfhi", "pf / wordMod", "Rust shift and cast to the high u32", {"pf"}),
            ("pglo", "pg % wordMod", "Rust cast to the low u32", {"pg"}),
            ("pghi", "pg / wordMod", "Rust shift and cast to the high u32", {"pg"}),
            ("d", "delta % wordMod", "Rust cast of two_delta to u32", {"delta"}),
            (
                "st",
                "(⟨pflo, pfhi, pglo, pghi, d, k, 0, 0, 0⟩ : BatchState)",
                "initial assembly registers and flags",
                {"pflo", "pfhi", "pglo", "pghi", "d", "k"},
            ),
            ("st", "batchRound^[k] st", "public-count assembly loop", {"k", "st"}),
            ("pf", "join32 st.pflo st.pfhi", "join the returned packed f words", {"st"}),
            ("pg", "join32 st.pglo st.pghi", "join the returned packed g words", {"st"}),
            ("delta", "signExtend32 st.d", "sign-extend the returned u32", {"st"}),
            ("uv", "unpackWords k pf", "Rust unpack(k, pf)", {"k", "pf"}),
            ("qr", "unpackWords k pg", "Rust unpack(k, pg)", {"k", "pg"}),
        ],
        "  ⟨delta, uv.1, uv.2, qr.1, qr.2⟩",
        ["delta", "uv", "qr"],
    )
    return [finish_routine, round_routine, batch_routine]


