def _function_with_asm_placeholder(function_source: str) -> tuple[str, str]:
    """Normalize a function, replacing its unique ``asm!(...)`` invocation by ``ASM``."""
    masked = asm_source.masked_noncode(function_source)
    matches = list(re.finditer(r"\basm\s*!\s*\(", masked))
    if len(matches) != 1:
        raise GenerationError(f"expected one asm! invocation, found {len(matches)}")
    match = matches[0]
    opening = masked.find("(", match.start())
    closing = asm_source.matching_delimiter(function_source, opening, "(", ")")
    normalized = asm_source.code_without_trivia(
        function_source[: match.start()] + "asm!(ASM)" + function_source[closing + 1 :]
    )
    return normalized, function_source[opening + 1 : closing]


def _validate_exact_function(source: str, function: str, expected: str) -> str:
    function_source = _top_level_function(source, function)
    if "ASM" in expected:
        normalized, asm_inner = _function_with_asm_placeholder(function_source)
    else:
        normalized = asm_source.code_without_trivia(function_source)
        asm_inner = ""
    if normalized != asm_source.code_without_trivia(expected):
        raise GenerationError(
            f"{function}: surrounding Rust differs from the checked transcription"
        )
    return asm_inner


class SkeletonBackend(gen.SkeletonBackend):
    """ARMv7E-M grouping and 32-bit proof facts for the shared traversal."""

    def prepare(self, emitter, entries):
        entries = [dict(entry) for entry in entries]
        names = gen.ssa_names(entries)
        i = 0
        while i < len(entries):
            kind = entries[i]["fact"][0]
            if kind not in ("adds", "adcs", "subs", "rsbs", "sbcs", "umaal"):
                i += 1
                continue
            pc = entries[i]["pc"]
            group_count = 1
            while i + group_count < len(entries) and entries[i + group_count]["pc"] == pc:
                group_count += 1
            entries[i]["group"] = list(
                zip(entries[i : i + group_count], names[i : i + group_count])
            )
            entries[i]["group_label"] = names[i + 1] if group_count == 3 else names[i]
            i += group_count
        # ARM words are 32-bit, so this backend emits its own bound hypotheses instead of
        # `word_step`'s shared 64-bit bounds.
        return gen.SkeletonPreparation(entries, names, clear_values=emitter.clear_values)

    def fact(self, kind, ops, context):
        nm = context.name

        def bound32(name, expression, proof="Nat.mod_lt _ (Nat.two_pow_pos _)"):
            context.eq(name, expression)
            context.lines.append(
                f"  have b_{name} : {name} < 2^32 := by rw [e_{name}]; exact {proof}"
            )
            context.bnd[name] = f"b_{name}"

        if kind == "word_state_load":
            argument, field, projection = ops
            context.eq(nm, f"{argument}.{field}")
            context.lines.append(
                f"  have b_{nm} : {nm} < 2^32 := by rw [e_{nm}]; exact h{argument}.{projection}"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "word_load":
            argument, limb, half = ops
            expression = f"{argument}.{limb} % 2^32" if half == 0 else f"{argument}.{limb} / 2^32"
            context.eq(nm, expression)
            if half == 0:
                proof = "Nat.mod_lt _ (Nat.two_pow_pos _)"
            else:
                hypothesis = gen.BOUND_HYPS.get(argument, f"h{argument}")
                proof = (
                    f"Nat.div_lt_of_lt_mul (lt_of_lt_of_eq "
                    f"{hypothesis}.{gen.proj(argument, limb)} (by norm_num))"
                )
            context.lines.append(f"  have b_{nm} : {nm} < 2^32 := by")
            context.lines.append(f"    rw [e_{nm}]; exact {proof}")
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "zero":
            if not ops:
                context.eq(nm, "0")
                context.lines.append(f"  have b_{nm} : {nm} < 2^32 := by rw [e_{nm}]; decide")
                context.bnd[nm] = f"b_{nm}"
            else:
                (value,) = ops
                context.eq(nm, f"(if {value} = 0 then 1 else 0)")
                context.lines.append(
                    f"  have b_{nm} : {nm} ≤ 1 := by rw [e_{nm}]; split <;> decide"
                )
                context.bnd[nm] = f"b_{nm}"
                context.unit_bound.add(nm)
            return True
        if kind == "branch":
            (flag,) = ops
            context.eq(nm, f"(if {flag} = 0 then 1 else 0)")
            context.lines.append(f"  have b_{nm} : {nm} ≤ 1 := by rw [e_{nm}]; split <;> decide")
            context.bnd[nm] = f"b_{nm}"
            context.unit_bound.add(nm)
            return True
        if kind == "param":
            (parameter,) = ops
            context.eq(nm, parameter)
            context.lines.append(
                f"  have b_{nm} : {nm} < 2^32 := by rw [e_{nm}]; exact h{parameter}"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind in ("adds", "adcs", "subs", "rsbs", "sbcs"):
            if kind == "adds":
                a, b = ops
                carry = "0"
            else:
                a, b, carry = ops
            if (
                kind == "rsbs"
                and len(context.group_names) == 2
                and context.group_entries[1][0]["name"] == "c"
            ):
                flag_name = context.group_names[1]
                value = f"({a} + 2^32 - {b} - (1 - {carry}))"
                context.eq(flag_name, f"{value} / 2^32")
                context.lines.append(f"  have b_{flag_name} : {flag_name} ≤ 1 := by")
                context.lines.append(
                    f"    rw [e_{flag_name}]; exact "
                    f"subc32_carry_le_one {a} {b} {carry} {context.lt64(a)}"
                )
                context.lines.append(f"  clear e_{flag_name}")
                context.ren[context.group_entries[1][0]["name"]] = flag_name
                context.bnd[flag_name] = f"b_{flag_name}"
                context.unit_bound.add(flag_name)
                context.consumed = 2
                return True
            if len(context.group_names) == 2 and context.group_entries[1][0]["name"] != "c":
                value_name = context.group_names[1]
                if kind in ("adds", "adcs"):
                    value = f"({a} + {b} + {carry})"
                else:
                    value = f"({a} + 2^32 - {b} - (1 - {carry}))"
                bound32(value_name, f"{value} % 2^32")
                context.ren[context.group_entries[1][0]["name"]] = value_name
                context.consumed = 2
                return True
            value_name, flag_name = context.group_names[1:3]
            if kind in ("adds", "adcs"):
                value = f"({a} + {b} + {carry})"
                linear = f"{value_name} + 2^32 * {flag_name} = {a} + {b} + {carry}"
                linear_proof = "Nat.mod_add_div _ _"
                flag_proof = (
                    f"addc32_carry_le_one {a} {b} {carry} {context.lt64(a)} "
                    f"{context.lt64(b)} {context.le1(carry)}"
                )
            else:
                value = f"({a} + 2^32 - {b} - (1 - {carry}))"
                linear = f"{value_name} + 2^32 * {flag_name} + {b} + 1 = {a} + 2^32 + {carry}"
                linear_proof = f"subc32_lin {a} {b} {carry} {context.lt64(b)} {context.le1(carry)}"
                flag_proof = f"subc32_carry_le_one {a} {b} {carry} {context.lt64(a)}"
            bound32(value_name, f"{value} % 2^32")
            context.eq(flag_name, f"{value} / 2^32")
            context.lines.append(f"  have l_{value_name} : {linear} := by")
            context.lines.append(f"    rw [e_{value_name}, e_{flag_name}]; exact {linear_proof}")
            context.lines.append(f"  have b_{flag_name} : {flag_name} ≤ 1 := by")
            context.lines.append(f"    rw [e_{flag_name}]; exact {flag_proof}")
            context.lines.append(f"  clear e_{value_name} e_{flag_name}")
            context.ren[context.group_entries[1][0]["name"]] = value_name
            context.ren[context.group_entries[2][0]["name"]] = flag_name
            context.bnd[flag_name] = f"b_{flag_name}"
            context.unit_bound.add(flag_name)
            context.consumed = 3
            return True
        if kind == "add":
            a, b = ops
            bound32(nm, f"({a} + {b}) % 2^32")
            return True
        if kind == "rsb":
            a, b = ops
            bound32(nm, f"({b} + 2^32 - {a}) % 2^32")
            return True
        if kind in ("adc", "sbc"):
            a, b, carry = ops
            if kind == "adc":
                expression = f"({a} + {b} + {carry})"
                bound32(nm, f"{expression} % 2^32")
                context.lines.append(f"  obtain ⟨k_{nm}, b_k_{nm}, l_{nm}⟩ :")
                context.lines.append(f"      ∃ k, k ≤ 1 ∧ {nm} + 2^32 * k = {a} + {b} + {carry} :=")
                context.lines.append(
                    f"    ⟨{expression} / 2^32, addc32_carry_le_one {a} {b} {carry} "
                    f"{context.lt64(a)} {context.lt64(b)} {context.le1(carry)},"
                )
                context.lines.append(f"      by rw [e_{nm}]; exact Nat.mod_add_div _ _⟩")
                context.lines.append(f"  clear e_{nm}")
            else:
                expression = f"({a} + 2^32 - {b} - (1 - {carry}))"
                bound32(nm, f"{expression} % 2^32")
            return True
        if kind == "umaal":
            low, high, a, b = ops
            total = f"({a} * {b} + {low} + {high})"
            low_name, high_name = context.group_names[1:3]
            bound32(low_name, f"{total} % 2^32")
            context.eq(high_name, f"{total} / 2^32")
            context.lines.append(
                f"  have m_{high_name} : {a} * {b} ≤ (2^32 - 1) * (2^32 - 1) := "
                f"Nat.mul_le_mul (Nat.le_sub_one_of_lt {context.lt64(a)}) "
                f"(Nat.le_sub_one_of_lt {context.lt64(b)})"
            )
            context.lines.append(f"  have t_{high_name} : {total} < 2^64 := by omega")
            context.lines.append(f"  have b_{high_name} : {high_name} < 2^32 := by")
            context.lines.append(
                f"    rw [e_{high_name}]; exact Nat.div_lt_of_lt_mul "
                f"(lt_of_lt_of_eq t_{high_name} (by norm_num))"
            )
            context.lines.append(
                f"  have d_{high_name} : {low_name} + 2^32 * {high_name} = {total} := by"
            )
            context.lines.append(f"    rw [e_{low_name}, e_{high_name}]; exact Nat.mod_add_div _ _")
            context.lines.append(f"  clear e_{low_name} e_{high_name}")
            context.ren[context.group_entries[1][0]["name"]] = low_name
            context.ren[context.group_entries[2][0]["name"]] = high_name
            context.bnd[low_name] = f"b_{low_name}"
            context.bnd[high_name] = f"b_{high_name}"
            context.consumed = 3
            return True
        if kind == "eor":
            a, b = ops
            bound32(nm, f"({a} ^^^ {b}) % 2^32", "Nat.mod_lt _ (Nat.two_pow_pos _)")
            context.lines.append(
                f"  have w_{nm} : ({a} ^^^ {b}) < 2^32 := Nat.xor_lt_two_pow "
                f"{context.lt64(a)} {context.lt64(b)}"
            )
            return True
        if kind == "and":
            a, b = ops
            context.eq(nm, f"andw {a} {b}")
            context.lines.append(f"  have b_{nm} : {nm} < 2^32 := by")
            context.lines.append(f"    rw [e_{nm}]; exact Nat.and_lt_two_pow {a} {context.lt64(b)}")
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "lsr":
            a, k = ops
            context.eq(nm, f"{a} / 2^{k}")
            context.lines.append(f"  have b_{nm} : {nm} < 2^32 := by")
            context.lines.append(
                f"    rw [e_{nm}]; exact lt_of_le_of_lt (Nat.div_le_self _ _) {context.lt64(a)}"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "asr":
            a, k = ops
            context.eq(nm, f"asr32 {a} {k}")
            context.lines.append(f"  have b_{nm} : {nm} < 2^32 := by")
            if k == 1:
                context.lines.append(f"    rw [e_{nm}]; exact asr32_one_lt {a} {context.lt64(a)}")
            else:
                context.lines.append(
                    f"    rw [e_{nm}, asr32]; split <;> norm_num [wordMod] at * <;> omega"
                )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "orr_lsl":
            a, b, k = ops
            context.eq(nm, f"orr32 {a} (lsl32 {b} {k})")
            context.lines.append(
                f"  have b_{nm} : {nm} < 2^32 := by rw [e_{nm}]; "
                "exact Nat.mod_lt _ (Nat.two_pow_pos _)"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind in ("fst", "snd"):
            if context.index == 0:
                raise ValueError(f"{kind} fact has no source binding")
            source = context.names[context.index - 1]
            context.eq(nm, f"{source}.{1 if kind == 'fst' else 2}")
            return True
        if kind == "composition":
            (expression,) = ops
            # Composition expressions are recorded as source-derived Lean text. Resolve each
            # register/let identifier to its current SSA name, just as the shared traversal does
            # for primitive operands; function names, fields, and numeric literals are unchanged.
            expression = re.sub(
                r"\b[A-Za-z_]\w*\b",
                lambda match: context.ren.get(match.group(0), match.group(0)),
                expression,
            )
            context.eq(nm, expression)
            # Composition contracts provide these bounds in their annotation blocks, just as
            # `callout` entries do. Keep the generated lets unbounded until those annotations.
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "combine32":
            low, high = ops
            context.eq(nm, f"{low} + 2^32 * {high}")
            context.lines.append(f"  have b_{nm} : {nm} < 2^64 := by")
            context.lines.append(
                f"    rw [e_{nm}]; clear * - {context.lt64(low)} {context.lt64(high)}; omega"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        if kind == "mov":
            (value,) = ops
            context.eq(nm, value)
            context.lines.append(
                f"  have b_{nm} : {nm} < 2^32 := by rw [e_{nm}]; exact {context.lt64(value)}"
            )
            context.bnd[nm] = f"b_{nm}"
            return True
        return False


