def emit_routine(source: str, config: RoutineConfig) -> Routine:
    parsed = parse_function(source, config)
    directions = asm_source.declaration_directions(parsed, config.rust_name)
    pointer_bindings: dict[str, str] = {}
    if config.memory:
        for declaration in parsed.declarations:
            pointer = re.fullmatch(r"([A-Za-z_]\w*)\.(as_ptr|as_mut_ptr)\(\)", declaration.value)
            if pointer:
                pointer_bindings[declaration.name] = pointer.group(1)
    emitter = Emitter(directions, pointer_bindings)

    for declaration in parsed.declarations:
        if declaration.kind in ("in", "inout"):
            pointer = re.fullmatch(r"([A-Za-z_]\w*)\.(as_ptr|as_mut_ptr)\(\)", declaration.value)
            if pointer:
                target, method = pointer.groups()
                if not config.memory:
                    raise GenerationError(
                        f"{config.rust_name}: pointer operand {declaration.name} is unsupported"
                    )
                if method == "as_ptr" and target in config.args:
                    emitter.bind_pointer(declaration.name, target)
                elif (
                    method == "as_mut_ptr"
                    and parsed.zero_arrays.get(target) == 4
                    and parsed.returns == (target,)
                ):
                    emitter.bind_zero_memory(declaration.name)
                else:
                    raise GenerationError(
                        f"{config.rust_name}: unsupported or uninitialized pointer target "
                        f"{declaration.value}"
                    )
            elif declaration.value in config.args:
                expression = declaration.value
                emitter.bind_argument(declaration.name, expression)
            elif declaration.value in parsed.locals:
                expression, index = parsed.locals[declaration.value]
                if index is not None:
                    raise GenerationError(
                        f"{config.rust_name}: unsupported indexed input operand {declaration.value}"
                    )
                emitter.bind_argument(declaration.name, expression)
            else:
                raise GenerationError(
                    f"{config.rust_name}: unsupported input operand expression {declaration.value}"
                )
        elif declaration.kind != "out":
            raise GenerationError(
                f"{config.rust_name}: unsupported operand direction {declaration.kind}"
            )

    for pc, instruction in enumerate(parsed.instructions):
        emitter.pc = pc
        emitter.emit_instruction(instruction)

    if config.memory:
        if set(pointer_bindings) != {"value", "modulus", "out"}:
            raise GenerationError(
                f"{config.rust_name}: expected value, modulus, and out pointer operands"
            )
        offsets = list(range(0, 32, 4))
        expected_accesses = {
            "value": offsets + offsets,
            "modulus": offsets,
            "out": offsets + [offset for offset in offsets for _ in range(2)],
        }
        for pointer, expected_offsets in expected_accesses.items():
            if emitter.used_offsets[pointer] != expected_offsets:
                raise GenerationError(
                    f"{config.rust_name}: {pointer} memory offsets differ: "
                    f"expected {expected_offsets}, found {emitter.used_offsets[pointer]}"
                )
        result_registers = []
        for limb, offset in enumerate(range(0, 32, 8)):
            low = emitter.memory.get(("out", offset))
            high = emitter.memory.get(("out", offset + 4))
            if low is None or high is None:
                raise GenerationError(f"{config.rust_name}: output limb {limb} is uninitialized")
            name = f"result{limb}"
            emitter.emit(
                name,
                f"{low} + wordMod * {high}",
                "combine output words",
                reads=(low, high),
                fact=("combine32", low, high),
            )
            result_registers.append(name)
    else:
        result_registers = list(
            asm_source.returned_registers(
                parsed,
                config.rust_name,
                discarded_outputs=set(config.discarded_outputs),
            )
        )
        for register in result_registers:
            if register not in emitter.written:
                raise GenerationError(
                    f"{config.rust_name}: output register {register} was never written"
                )

    if config.memory:
        result_type = "Limbs"
    elif config.result_count == 2:
        result_type = "Nat × Nat"
    else:
        result_type = " × ".join("Nat" for _ in range(config.result_count))
    argument_type = "Limbs" if config.memory else "Nat"
    signature = (
        f"def {config.lean_name} ({' '.join(config.args)} : {argument_type}) : {result_type} :="
    )
    result = (
        f"  ⟨{', '.join(result_registers)}⟩"
        if config.memory
        else f"  ({', '.join(result_registers)})"
    )
    return Routine(
        config.doc,
        signature,
        emitter.render(result_registers),
        result,
        config.lean_name,
        emitter,
        result_registers,
    )


def all_routines(source: str | None = None) -> list[Routine]:
    source = SOURCE.read_text() if source is None else source
    validate_asm_block_inventory(source)
    ordinary = [emit_routine(source, config) for config in ROUTINES]
    return (
        ordinary[:-1]
        + emit_from_mont_routines(source)
        + emit_batch_routines(source)
        + [emit_divstep59_routine(source), ordinary[-1]]
    )


def gen_program(source: str | None = None) -> str:
    routines = all_routines(source)
    return HEADER + "\n".join(routine.text(COMMENT_COLUMN) for routine in routines) + FOOTER


def generated_outputs():
    """Return the ARMv7E-M generated path and contents without writing files."""
    return [(OUTPUT, gen_program())]
