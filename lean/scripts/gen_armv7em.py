"""ARMv7E-M backend for the unified Lean transcription generator.

The shared :mod:`asm_source` parser extracts the register-only word primitives and
the fixed-offset ``cond_sub`` block from ``src/asm/armv7em.rs``. This module validates
the small Thumb-2 instruction subset, register and carry initialization, operand
directions and overlap, and the exact initialized-memory access schedule, then emits
their mechanical SSA-style Lean transcription.

The backend explicitly inventories every ``asm!`` block in the Rust source, so the
remaining untranscribed memory and loop blocks cannot disappear unnoticed. Invoke it
through ``python3 lean/scripts/gen.py``.
"""

