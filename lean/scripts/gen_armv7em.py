def asm_block_inventory(source: str) -> tuple[str, ...]:
    """Return every top-level function containing inline assembly, in source order."""
    masked = asm_source.masked_noncode(source)
    functions = re.finditer(
        r"(?m)^(?:pub(?:\([^)]*\))?\s+)?fn\s+([A-Za-z_]\w*)\s*\(",
        masked,
    )
    blocks = []
    for match in functions:
        signature_open = masked.find("(", match.start())
        signature_close = asm_source.matching_delimiter(source, signature_open, "(", ")")
        body_open = masked.find("{", signature_close)
        if body_open < 0:
            raise GenerationError(f"{match.group(1)}: missing function body")
        body_close = asm_source.matching_delimiter(source, body_open, "{", "}")
        if re.search(r"\basm\s*!\s*\(", masked[body_open + 1 : body_close]):
            blocks.append(match.group(1))
    return tuple(blocks)


def validate_asm_block_inventory(source: str) -> None:
    found = asm_block_inventory(source)
    if found != ASM_BLOCKS:
        raise GenerationError(
            f"ARM asm block inventory differs: expected {list(ASM_BLOCKS)}, found {list(found)}"
        )


def _top_level_function(source: str, function: str) -> str:
    """Return the unique top-level function definition named ``function``."""
    masked = asm_source.masked_noncode(source)
    matches = list(re.finditer(rf"(?m)^fn\s+{re.escape(function)}\s*\(", masked))
    if len(matches) != 1:
        raise GenerationError(
            f"expected exactly one top-level `fn {function}(`, found {len(matches)}"
        )
    match = matches[0]
    signature_open = masked.find("(", match.start())
    signature_close = asm_source.matching_delimiter(source, signature_open, "(", ")")
    body_open = masked.find("{", signature_close)
    if body_open < 0:
        raise GenerationError(f"{function}: missing function body")
    body_close = asm_source.matching_delimiter(source, body_open, "{", "}")
    return source[match.start() : body_close + 1]


def _inline_asm_function(source: str, function: str) -> str:
    """Return the unique top-level definition of ``function`` containing ``asm!``.

    The Rust source also defines a non-ARM arithmetic model with each name. The
    architecture backend selects by the mechanically observable inline-assembly
    body, then lets the shared parser consume that complete function unchanged.
    """
    masked = asm_source.masked_noncode(source)
    matches = list(re.finditer(rf"(?m)^fn\s+{re.escape(function)}\s*\(", masked))
    candidates = []
    for match in matches:
        signature_open = masked.find("(", match.start())
        signature_close = asm_source.matching_delimiter(source, signature_open, "(", ")")
        body_open = masked.find("{", signature_close)
        if body_open < 0:
            raise GenerationError(f"{function}: missing function body")
        body_close = asm_source.matching_delimiter(source, body_open, "{", "}")
        body = masked[body_open + 1 : body_close]
        if re.search(r"\basm\s*!\s*\(", body):
            candidates.append(source[match.start() : body_close + 1])
    if len(candidates) != 1:
        raise GenerationError(
            f"expected exactly one top-level `fn {function}(` containing asm!, "
            f"found {len(candidates)}"
        )
    return candidates[0]


def parse_function(source: str, config: RoutineConfig) -> ParsedFunction:
    function_source = (
        source if config.rust_name == "cond_sub" else _inline_asm_function(source, config.rust_name)
    )
    return asm_source.parse_function(
        function_source,
        config.rust_name,
        config.args,
        config.result_count,
        reserved_names=RESERVED_OPERAND_NAMES,
        fixed_registers={"r2", "r3"} if config.memory else frozenset(),
        allowed_options={"nostack"} if config.memory else {"pure", "nomem", "nostack"},
        required_options={"nostack"} if config.memory else {"pure", "nomem", "nostack"},
    )


def parse_from_mont(source: str) -> ParsedFunction:
    """Parse the fixed-register conversion block under its exact operand contract."""
    return asm_source.parse_function(
        source,
        "from_mont",
        ["value", "modulus", "inv"],
        8,
        reserved_names=RESERVED_OPERAND_NAMES,
        fixed_registers=set(FROM_MONT_REGISTERS),
        fixed_register_kinds={"in", "out", "inout"},
        allowed_options={"pure", "readonly", "nostack"},
        required_options={"pure", "readonly", "nostack"},
    )


class Emitter(gen.Emitter):
    """Validate the supported Thumb-2 subset and record the shared binding IR."""

    def __init__(
        self,
        directions: dict[str, str],
        pointers: dict[str, str] | None = None,
        *,
        loop_control: bool = False,
        clear_values: bool = True,
    ):
        super().__init__()
        self.directions = dict(directions)
        self.pointers = dict(pointers or {})
        self.memory: dict[tuple[str, int], str] = {}
        self.used_offsets: dict[str, list[int]] = {pointer: [] for pointer in self.pointers}
        self.carry_valid = False
        self.zero_valid = False
        self.loop_control = loop_control
        self.clear_values = clear_values
        self.loop_label_seen = False
        self.branch_seen = False
        self.written: set[str] = set()

    @staticmethod
    def split_instruction(text: str) -> tuple[str, list[str]]:
        found = re.fullmatch(r"\s*([A-Za-z][A-Za-z0-9]*(?:\.w)?)\s*(.*?)\s*", text)
        if not found:
            raise GenerationError(f"cannot parse instruction {text!r}")
        op, rest = found.groups()
        operands: list[str] = []
        start = 0
        bracket_depth = 0
        for index, character in enumerate(rest):
            if character == "[":
                bracket_depth += 1
            elif character == "]":
                bracket_depth -= 1
                if bracket_depth < 0:
                    raise GenerationError(f"unmatched memory bracket in instruction {text!r}")
            elif character == "," and bracket_depth == 0:
                operands.append(rest[start:index].strip())
                start = index + 1
        if bracket_depth:
            raise GenerationError(f"unmatched memory bracket in instruction {text!r}")
        if rest:
            operands.append(rest[start:].strip())
        if any(not operand for operand in operands):
            raise GenerationError(f"empty operand in instruction {text!r}")
        return op.lower().removesuffix(".w"), operands

    @staticmethod
    def require_count(op: str, operands: Sequence[str], count: int) -> None:
        if len(operands) != count:
            raise GenerationError(f"{op} expects {count} operands, got {len(operands)}")

    @staticmethod
    def _reads(*operands: str) -> set[str]:
        return {operand for operand in operands if re.fullmatch(r"[A-Za-z_]\w*", operand)}

    def _check_declared(self, register: str) -> None:
        if register not in self.directions:
            raise GenerationError(f"undeclared register {register}")

    def parse_address(self, token: str) -> tuple[str, int]:
        match = re.fullmatch(
            r"\[(?:\{([A-Za-z_]\w*)\}|(r(?:[0-9]|1[0-4]))),\s*#(0|[1-9][0-9]*)\]",
            token,
        )
        if not match:
            raise GenerationError(f"unsupported memory operand {token}")
        named, fixed, offset_text = match.groups()
        pointer = named or fixed
        if pointer not in self.pointers:
            raise GenerationError(f"memory base {pointer} is not a declared pointer")
        offset = int(offset_text)
        if offset % 4 or offset < 0 or offset > 28:
            raise GenerationError(f"memory offset must be one of 0, 4, ..., 28: {offset}")
        self.used_offsets[pointer].append(offset)
        return pointer, offset

    def parse_register(self, token: str) -> str:
        if "[" in token or "]" in token:
            raise GenerationError(f"memory operands are unsupported: {token}")
        match = re.fullmatch(r"\{([A-Za-z_]\w*)\}", token)
        if match:
            register = match.group(1)
        elif token == "lr" and "r14" in self.directions:
            register = "r14"
        elif re.fullmatch(r"r(?:[0-9]|1[0-4])", token) and token in self.directions:
            register = token
        else:
            raise GenerationError(f"unsupported register operand {token}")
        self._check_declared(register)
        return register

    def read_register(self, token: str) -> str:
        register = self.parse_register(token)
        if register not in self.known:
            if self.directions[register] == "out":
                raise GenerationError(f"output-only register {register} read before being written")
            raise GenerationError(f"register {register} read before being written")
        return register

    def write_register(self, token: str) -> str:
        register = self.parse_register(token)
        if self.directions[register] == "in":
            raise GenerationError(f"input-only register {register} cannot be written")
        self.written.add(register)
        return register

    def read_value(self, token: str) -> str:
        if "[" in token or "]" in token:
            raise GenerationError(f"memory operands are unsupported: {token}")
        immediate = re.fullmatch(r"#(0|[1-9][0-9]*|0x[0-9a-fA-F]+)", token)
        if immediate:
            value = int(immediate.group(1), 0)
            if value >= 2**32:
                raise GenerationError(f"immediate does not fit a 32-bit word: {token}")
            return immediate.group(1).lower()
        return self.read_register(token)

    @staticmethod
    def shift_amount(token: str) -> int:
        match = re.fullmatch(r"#(0|[1-9][0-9]*)", token)
        if not match:
            raise GenerationError(f"unsupported shift amount {token}")
        amount = int(match.group(1))
        if amount >= 32:
            raise GenerationError(f"32-bit shift amount out of range: {token}")
        return amount

    @staticmethod
    def slot_name(pointer: str, offset: int) -> str:
        return f"{pointer}_{offset}"

    def bind_pointer(self, pointer: str, argument: str) -> None:
        self._check_declared(pointer)
        for offset in range(0, 32, 4):
            limb = offset // 8
            half = offset % 8
            name = self.slot_name(pointer, offset)
            expression = (
                f"{argument}.l{limb} % wordMod" if half == 0 else f"{argument}.l{limb} / wordMod"
            )
            self.bind(
                name,
                expression,
                f"input {pointer}[{offset}]",
                reads=(),
                load=True,
                fact=("word_load", argument, f"l{limb}", half),
            )
            self.memory[(pointer, offset)] = name

    def bind_zero_memory(self, pointer: str) -> None:
        self._check_declared(pointer)
        for offset in range(0, 32, 4):
            name = self.slot_name(pointer, offset)
            self.bind(
                name,
                "0",
                f"zero-initialized {pointer}[{offset}]",
                reads=(),
                load=True,
                fact=("zero",),
            )
            self.memory[(pointer, offset)] = name

    def bind_argument(self, register: str, expression: str) -> None:
        self._check_declared(register)
        if register in self.known:
            raise GenerationError(f"duplicate initial binding for {register}")
        self.bind(
            register,
            expression,
            f"input {register}",
            reads=(),
            fact=("param", expression),
        )

    def emit(
        self, name: str, expr: str, comment=None, *, reads=(), fact=None, note=None, optional=False
    ) -> None:
        self.bind(name, expr, comment, reads=reads, fact=fact, note=note)
        if optional:
            self.entries[-1]["optional"] = True

    def require_carry(self, text: str) -> None:
        if not self.carry_valid:
            raise GenerationError(f"carry flag read while invalid: {text}")

    def emit_instruction(self, text: str) -> None:
        if text == "2:":
            if not self.loop_control or self.loop_label_seen:
                raise GenerationError(f"unsupported or duplicate loop label: {text}")
            if any(entry["pc"] is not None for entry in self.entries):
                raise GenerationError(f"loop label must precede every instruction: {text}")
            self.loop_label_seen = True
            return
        op, operands = self.split_instruction(text)
        try:
            if op == "bne":
                self.require_count(op, operands, 1)
                if not self.loop_control or operands[0] != "2b" or not self.loop_label_seen:
                    raise GenerationError("unsupported branch target or placement")
                if not self.zero_valid:
                    raise GenerationError("zero flag read while invalid")
                if self.branch_seen:
                    raise GenerationError("duplicate loop branch")
                self.branch_seen = True
                self.emit(
                    "branch",
                    "(if z = 0 then 1 else 0)",
                    text,
                    reads=("z",),
                    fact=("branch", "z"),
                )
            elif op == "ldr":
                self.require_count(op, operands, 2)
                pointer, offset = self.parse_address(operands[1])
                slot = self.memory.get((pointer, offset))
                if slot is None:
                    raise GenerationError(f"uninitialized memory read {pointer}[{offset}]")
                dst = self.write_register(operands[0])
                self.emit(dst, slot, text, reads=(slot,), fact=("mov", slot))
            elif op == "str":
                self.require_count(op, operands, 2)
                value = self.read_register(operands[0])
                pointer, offset = self.parse_address(operands[1])
                slot = self.slot_name(pointer, offset)
                self.emit(slot, value, text, reads=(value,), fact=("mov", value))
                self.memory[(pointer, offset)] = slot
            elif op in ("adds", "adcs", "subs"):
                self.require_count(op, operands, 3)
                left = self.read_value(operands[1])
                right = self.read_value(operands[2])
                dst = self.write_register(operands[0])
                pair = "addc32" if op in ("adds", "adcs") else "subc32"
                carry = "c" if op == "adcs" else ("0" if op == "adds" else "1")
                if op == "adcs":
                    self.require_carry(text)
                temporary = (
                    "adcs_pair"
                    if op == "adcs"
                    else "s"
                    if op == "adds"
                    else ("sub" if "d" in self.directions else "d")
                )
                self.emit(
                    temporary,
                    f"{pair} {left} {right} {carry}",
                    text,
                    reads=self._reads(left, right, carry),
                    fact=(op, left, right) if op == "adds" else (op, left, right, carry),
                )
                projection_reads = (temporary,)
                self.emit(
                    dst,
                    f"{temporary}.1",
                    reads=projection_reads,
                    fact=("fst",),
                    note=f"  `-> {dst}",
                )
                self.emit(
                    "c",
                    f"{temporary}.2",
                    reads=projection_reads,
                    fact=("snd",),
                    note="  `-> carry",
                )
                self.carry_valid = True
                if op == "subs" and self.loop_control:
                    self.emit(
                        "z",
                        f"(if {dst} = 0 then 1 else 0)",
                        reads=(dst,),
                        fact=("zero", dst),
                        note="  `-> zero",
                    )
                    self.zero_valid = True
            elif op in ("rsbs", "sbcs"):
                self.require_count(op, operands, 3)
                if op == "sbcs":
                    self.require_carry(text)
                    left = self.read_value(operands[1])
                    right = self.read_value(operands[2])
                    carry = "c"
                else:
                    value = self.read_value(operands[1])
                    if operands[2] != "#0":
                        raise GenerationError("rsbs supports only reverse subtraction from #0")
                    left, right, carry = "0", value, "1"
                dst = self.write_register(operands[0])
                temporary = "sub" if "d" in self.directions else "d"
                self.emit(
                    temporary,
                    f"subc32 {left} {right} {carry}",
                    text,
                    reads=self._reads(left, right, carry),
                    fact=(op, left, right, carry),
                )
                self.emit(
                    dst,
                    f"{temporary}.1",
                    text if op == "rsbs" else None,
                    reads=(temporary,),
                    fact=("fst",),
                    note=f"  `-> {dst}" if op != "rsbs" else None,
                    optional=op == "rsbs",
                )
                self.emit(
                    "c", f"{temporary}.2", reads=(temporary,), fact=("snd",), note="  `-> carry"
                )
                self.carry_valid = True
            elif op in ("adc", "sbc"):
                self.require_count(op, operands, 3)
                self.require_carry(text)
                left = self.read_value(operands[1])
                right = self.read_value(operands[2])
                dst = self.write_register(operands[0])
                if op == "adc":
                    expression = f"(addc32 {left} {right} c).1"
                else:
                    expression = f"(subc32 {left} {right} c).1"
                self.emit(
                    dst,
                    expression,
                    text,
                    reads=self._reads(left, right, "c"),
                    fact=(op, left, right, "c"),
                )
            elif op == "mov":
                self.require_count(op, operands, 2)
                value = self.read_value(operands[1])
                dst = self.write_register(operands[0])
                self.emit(dst, value, text, reads=self._reads(value), fact=("mov", value))
            elif op in ("add", "rsb"):
                self.require_count(op, operands, 3)
                left = self.read_value(operands[1])
                right = self.read_value(operands[2])
                dst = self.write_register(operands[0])
                expression = (
                    f"({left} + {right}) % wordMod"
                    if op == "add"
                    else f"({right} + wordMod - {left}) % wordMod"
                )
                self.emit(
                    dst,
                    expression,
                    text,
                    reads=self._reads(left, right),
                    fact=(op, left, right),
                )
            elif op in ("eor", "and"):
                self.require_count(op, operands, 3)
                left = self.read_value(operands[1])
                right = self.read_value(operands[2])
                dst = self.write_register(operands[0])
                function = "eor32" if op == "eor" else "andw"
                self.emit(
                    dst,
                    f"{function} {left} {right}",
                    text,
                    reads=self._reads(left, right),
                    fact=(op, left, right),
                )
            elif op in ("lsr", "asr"):
                self.require_count(op, operands, 3)
                value = self.read_register(operands[1])
                amount = self.shift_amount(operands[2])
                dst = self.write_register(operands[0])
                self.emit(
                    dst,
                    f"{op}32 {value} {amount}",
                    text,
                    reads=(value,),
                    fact=(op, value, amount),
                )
            elif op == "orr":
                self.require_count(op, operands, 4)
                left = self.read_register(operands[1])
                right = self.read_register(operands[2])
                shift = re.fullmatch(r"lsl\s+#(0|[1-9][0-9]*)", operands[3])
                if not shift:
                    raise GenerationError(f"unsupported shifted operand {operands[3]}")
                amount = int(shift.group(1))
                if amount >= 32:
                    raise GenerationError(f"32-bit shift amount out of range: #{amount}")
                dst = self.write_register(operands[0])
                self.emit(
                    dst,
                    f"orr32 {left} (lsl32 {right} {amount})",
                    text,
                    reads=(left, right),
                    fact=("orr_lsl", left, right, amount),
                )
            elif op == "umaal":
                self.require_count(op, operands, 4)
                low = self.read_register(operands[0])
                high = self.read_register(operands[1])
                left = self.read_register(operands[2])
                right = self.read_register(operands[3])
                if low == high:
                    raise GenerationError("umaal destinations must be distinct")
                overlap = {low, high} & {left, right}
                if overlap:
                    raise GenerationError(
                        f"umaal destinations overlap input registers: {', '.join(sorted(overlap))}"
                    )
                self.write_register(operands[0])
                self.write_register(operands[1])
                self.emit(
                    "m",
                    f"umaal32 {low} {high} {left} {right}",
                    text,
                    reads=self._reads(low, high, left, right),
                    fact=("umaal", low, high, left, right),
                )
                self.emit(low, "m.1", reads=("m",), fact=("fst",), note=f"  `-> {low}")
                self.emit(high, "m.2", reads=("m",), fact=("snd",), note=f"  `-> {high}")
            else:
                raise GenerationError(f"unsupported instruction {op}: {text}")
        except GenerationError as error:
            if str(error).endswith(f": {text}"):
                raise
            raise GenerationError(f"{error}: {text}") from error


