# The high limb of both Pasta moduli, which the blocks bind as `const PASTA_HIGH_LIMB`.
PASTA_HIGH_LIMB = 1 << 62

HEADER = """/-
Copyright Supranational LLC (the routines, transcribed from Semolina v0.1.4).
Copyright (c) 2026 the pasta_curves contributors (the transcription).
-/
import PastaCurves.X86_64.Semantics

/-!
# The crate's inline x86-64 Pasta field blocks, transcribed

GENERATED by `lean/scripts/gen.py` from the `asm!` blocks in
`src/asm/x86_64.rs`; do not edit by hand. Each source instruction occurs in a trailing
comment on the let binding that models it. Registers are lexically rebound after
each write. The two identical full internal multiplication rounds are represented by
a generated helper after their flattened IRs have been compared modulo the source's
register rotation. `cf` and `ofl` model x86 CF and OF independently; the generator
rejects a read after an instruction that invalidates the corresponding flag. ZF and SF are
read off the word that set them (`zs`, bound by `test`, or the destination of `add`).

Pointer operands are represented only by reads of their four input limbs. The
generator accepts no stores, no address other than a declared read-only pointer
plus 0, 8, 16, or 24 bytes, and no register read before an input or instruction has
written it. The fixed RDX operand, 32-bit `:e` XOR-zero idiom, operand outputs, and
Rust return-tuple order are parsed from the source rather than inferred here.
-/

namespace PastaCurves.X86_64

-- A mechanical transcription intentionally retains dead architectural results.
set_option linter.unusedVariables false

"""

