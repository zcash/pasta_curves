def validate_high_limb(source: str) -> None:
    matches = re.findall(
        r"^\s*const\s+PASTA_HIGH_LIMB\s*:\s*u64\s*=\s*([^;]+);",
        source,
        re.MULTILINE,
    )
    if len(matches) != 1:
        raise GenerationError("expected exactly one PASTA_HIGH_LIMB declaration")
    expression = re.sub(r"\s+", "", matches[0])
    if expression != "1<<62" or PASTA_HIGH_LIMB != 0x4000000000000000:
        raise GenerationError("PASTA_HIGH_LIMB must be `1 << 62` (0x4000000000000000)")


# `mul`'s two full internal rounds agree once the accumulator registers are rotated; the rotation is
# derived by matching the rounds, from round 1's accumulator registers `entry`.
MUL_ROUNDS = RotatedRounds(
    ranges=((28, 63), (64, 99)),
    rhs="rhs",
    rhs_field="l{i}",
    entry=("be", "ce", "de", "ee", "ae"),
    result=("r1", "r2", "r3", "r4", "r0", "rdx"),
    round="mulMontRound",
    doc=(
        "One full internal round of `mulMont`: add `lhs * b` to the rotating five-limb "
        "accumulator, cancel its low limb with the Montgomery quotient, and shift by one limb. "
        "The source's flattened rounds 1 and 2 are checked to have this same binding IR modulo "
        "their accumulator-register rotation and RHS limb, and this round, instantiated at each "
        "of its two calls, is checked to flatten back to the source's round."
    ),
    state="MulMontAcc",
    state_doc=(
        "/-- The rotating five-limb accumulator of `mulMont`, together with the most recent\n"
        "Montgomery quotient. The next round does not read `q`; retaining it exposes the round "
        "invariant\nneeded by the block proof. -/"
    ),
    roles=(
        Role("r0", "r0", "accumulator limb 0"),
        Role("r1", "r1", "accumulator limb 1"),
        Role("r2", "r2", "accumulator limb 2"),
        Role("r3", "r3", "accumulator limb 3"),
        Role("r4", "r4", "accumulator limb 4"),
        Role("q", "q", "the most recent Montgomery quotient"),
    ),
    value=("r0", "r1", "r2", "r3", "r4"),
    value_doc="The value of the five accumulator limbs.",
    passed=("lhs", "modulus"),
    invariants=("inv",),
    arg="acc",
    load_register="rdx",
    param="b",
    scalar_comment="scalar argument",
    state_comment="accumulator argument",
)

# The macro arms (see `rust.parse_macros`) transcribed as round definitions, by (macro, arm).
# The body arm of `divstep!` finishes one step and starts the next; it reads and carries the
# registers of `roles`, and no flags: each step derives the flags it reads itself. The `first`
# and `last` arms, three instructions or one batch's start, stay expanded.
MACRO_ROUNDS = {
    ("divstep", ""): MacroRound(
        round="divstepRound",
        doc=(
            "one packed half-delta divstep: it finishes the step that the previous arm started, "
            "adding `t` to the packed `g`, halving it, and adding two to `two_delta`, and starts the "
            "next from the sign of the new `two_delta` and the parity of the new `g`"
        ),
        state="DivstepState",
        emit_struct=True,
        arg="st",
        call="step",
        roles=(
            Role("td", "two_delta", "`two_delta = 2δ`, as a two's-complement word"),
            Role("pf", "f", "the packed `f` word"),
            Role("pg", "g", "the packed `g` word"),
            Role("t", "t", "the term that the step adds to `g`: `f`, `-f`, or zero"),
            Role("z", "z", "zero, which the conditional moves take"),
        ),
    ),
}

TARGET = Target(
    X86_64_ISA,
    {**inversion.KINDS, "WideLimbs": tuple(f"l{i}" for i in range(8))},
    CONVENTIONS,
    consts={"PASTA_HIGH_LIMB": PASTA_HIGH_LIMB},
    rerollers={"mulMont": MUL_ROUNDS},
    macro_rounds=MACRO_ROUNDS,
    # Unlike AArch64's, this transcription keeps every architectural result, including dead flag
    # writes, and names each input by the Rust value it binds.
    dead_code=DeadCode.RETAIN,
    input_comment=lambda value, scalar: "scalar input" if scalar else f"input {value}",
)


def programs(source: str | None = None) -> list[Program]:
    """Every program of the transcription, in order."""
    source = SOURCE.read_text() if source is None else source
    validate_high_limb(source)
    return transcription.programs(source, BLOCKS, TARGET)


def text(source: str | None = None) -> str:
    """The transcription module: each definition with its comments aligned at its own column."""
    definitions = transcription.definitions(programs(source))
    return HEADER + definitions + FOOTER
