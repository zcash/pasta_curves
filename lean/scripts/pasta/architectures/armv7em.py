"""ARMv7E-M (`src/asm/armv7em.rs`): its blocks, how its rounds are factored, and its transcription.

The register-only word primitives (`adc`, `add_word`, `sbb`, `mac_word`, `inversion_mac_words`) and
the memory block `cond_sub` transcribe instruction for instruction. Three blocks are larger, and are
factored here into definitions their proofs can take one at a time; each factoring is checked
against the flat lifted block before it is used:

- `from_mont` is eight invocations of `from_mont_round!`, each on the accumulator rotated by one
  register, then a final reduction. The invocations must be one round under their rotations: the
  round is then split into its quotient prefix (itself three one-instruction helpers) and its sparse
  multiply/carry suffix, and the final reduction into its subtraction and its masked add-back. Each
  split must reconstruct the instructions it splits, in order.
- `batch` is a loop. Its body is one round, carried in a structure with the loop's public count and
  flags, and its last five instructions a helper of their own; the Rust around the block, and
  `divstep59`, which composes three batches, are compositions whose source must be exactly the Rust
  this module models.

The structures, the header, and the compositions are written here; everything else is generated
from the source, and the source's `asm!` blocks are inventoried, so that an added, removed, or renamed
block fails generation until this module decides how to cover it.
"""

