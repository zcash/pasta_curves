# A round is 21 instructions, the first after 9 loads; the final reduction is the last 31.
ROUND, FIRST_ROUND, FINAL = 21, 9, 177


def check_round_split(
    whole: Sequence[Node], prefix: Sequence[Node], suffix: Sequence[Node]
) -> None:
    """Require the round's quotient prefix and sparse suffix to cover PCs 0 to 2 and 3 to 20,
    and to be the round exactly."""
    covers(prefix, range(3), "quotient prefix")
    covers(suffix, range(3, ROUND), "sparse suffix")
    reconstructs(
        [prefix, suffix], whole, "factored helpers do not reconstruct the normalized round"
    )


def check_prefix_split(
    prefix: Sequence[Node],
    quotient: Sequence[Node],
    self_sub: Sequence[Node],
    mask: Sequence[Node],
) -> None:
    """Require the prefix's one-instruction helpers to cover PCs 0, 1 and 2, and to be the prefix
    exactly."""
    parts = (("quotient", quotient), ("self-subtraction", self_sub), ("mask", mask))
    for pc, (what, part) in enumerate(parts):
        if pcs(part) != [pc]:
            raise GenerationError(f"from_mont: {what} helper does not cover PC {pc}")
    reconstructs(
        [quotient, self_sub, mask],
        prefix,
        "short prefix helpers do not reconstruct PCs 0 through 2",
    )


def check_final_split(
    final: Sequence[Node], subtraction: Sequence[Node], addback: Sequence[Node]
) -> None:
    """Require the final reduction's subtraction and add-back to cover PCs 0 to 13 and 14 to 30,
    and to be the final reduction exactly."""
    if pcs(subtraction) != list(range(14)):
        raise GenerationError("from_mont: final subtraction helper does not cover PCs 0 through 13")
    if pcs(addback) != list(range(14, len(FROM_MONT_FINAL))):
        raise GenerationError("from_mont: final add-back helper does not cover PCs 14 through 30")
    reconstructs(
        [subtraction, addback], final, "final reduction helpers do not reconstruct PCs 0 through 30"
    )


def round_nodes(flat: Sequence[Node], site: int) -> list[Node]:
    """Round `site` (from 0) of the flat block, its registers renamed to the state's fields under
    the round's rotation, and its positions relative to its first instruction."""
    ring = [*FROM_MONT_ACCUMULATOR, "r0"]
    registers = ring[site:] + ring[:site]
    start = FIRST_ROUND + ROUND * site
    renaming = dict(zip(registers, (*FROM_MONT_STATE_FIELDS, "tmp"), strict=True))
    return normalized(flat, start, start + ROUND, renaming)


def final_nodes(flat: Sequence[Node]) -> list[Node]:
    """The final reduction of the flat block, its registers renamed to the state's fields, and its
    positions relative to its first instruction."""
    renaming = dict(zip(FROM_MONT_FINAL_REGISTERS, FROM_MONT_STATE_FIELDS, strict=True))
    final = normalized(flat, FINAL, FINAL + len(FROM_MONT_FINAL), renaming)
    if pcs(final) != list(range(len(FROM_MONT_FINAL))):
        raise GenerationError("from_mont: final reduction does not cover PCs 177 through 207")
    return final


def lift_from_mont(source: str) -> tuple[ParsedFunction, Armv7emLifter]:
    """The fixed-register conversion block, lifted flat, with its operand contract and the
    schedule of its memory reads checked."""
    parsed = rust.parse_function(
        source,
        "from_mont",
        ["value", "modulus", "inv"],
        8,
        reserved_names=RESERVED,
        fixed_registers=set(FROM_MONT_REGISTERS),
        fixed_register_kinds={"in", "out", "inout"},
        allowed_options={"pure", "readonly", "nostack"},
        required_options={"pure", "readonly", "nostack"},
    )
    declarations = tuple((d.name, d.kind, d.value, d.output) for d in parsed.declarations)
    if declarations != FROM_MONT_DECLARATIONS:
        raise GenerationError("from_mont: fixed-register declarations differ")
    returned = rust.returned_registers(parsed, "from_mont")
    expected_returned = ("r14", "r0", "r2", "r3", "r4", "r5", "r8", "r9")
    if returned != expected_returned:
        raise GenerationError(
            f"from_mont: returned registers differ: expected {expected_returned}, found {returned}"
        )
    flat = Armv7emLifter(rust.declaration_directions(parsed, "from_mont"))
    flat.bind_memory("r0", "value")
    flat.bind_memory("r1", "modulus")
    lift_all(flat, parsed.instructions)
    value_offsets = list(range(0, 32, 4))
    modulus_offsets = [4, 8, 12] * 10
    if flat.used_offsets["r0"] != value_offsets:
        raise GenerationError(
            f"from_mont: value memory offsets differ: expected {value_offsets}, "
            f"found {flat.used_offsets['r0']}"
        )
    if flat.used_offsets["r1"] != modulus_offsets:
        raise GenerationError(
            f"from_mont: modulus memory offsets differ: expected {modulus_offsets}, "
            f"found {flat.used_offsets['r1']}"
        )
    if parsed.instructions[FINAL:] != FROM_MONT_FINAL:
        raise GenerationError("from_mont: final borrow selection differs")
    return parsed, flat


def from_mont_programs(source: str) -> list[Program]:
    """`from_mont`, its rounds checked to be one round under their rotations and factored."""
    parsed, flat = lift_from_mont(source)
    fields = FROM_MONT_STATE_FIELDS
    ring = [*FROM_MONT_ACCUMULATOR, "r0"]
    rotations: list[list[str]] = []
    rounds: list[list[Node]] = []
    for site in range(8):
        registers = ring[site:] + ring[:site]
        rotations.append(registers)
        arm = ", ".join("lr" if register == "r14" else register for register in registers)
        start = FIRST_ROUND + ROUND * site
        origins = parsed.origins[start : start + ROUND]
        if len(origins) != ROUND or any(
            o is None or o.macro != "from_mont_round" or o.site != site or o.arm != arm
            for o in origins
        ):
            raise GenerationError(
                f"from_mont: macro call {site + 1} does not use the expected register rotation"
            )
        rounds.append(round_nodes(flat.nodes, site))
    if parsed.origins[:FIRST_ROUND] != (None,) * FIRST_ROUND or parsed.origins[FINAL:] != (
        (None,) * len(FROM_MONT_FINAL)
    ):
        raise GenerationError(
            "from_mont: instructions outside the eight macro calls changed origin"
        )
    if not rounds[0] or any(fingerprint(r) != fingerprint(rounds[0]) for r in rounds[1:]):
        raise GenerationError("from_mont: macro rounds differ after the exact register rotation")
    if tuple(rotations[-1][1:]) != FROM_MONT_FINAL_REGISTERS:
        raise GenerationError("from_mont: post-round-8 register mapping differs")
    state = {"st": fields}

    # The round, split at its first modulus load: PCs 0 to 2 compute the Montgomery quotient and
    # the carry cancelling the low word, PCs 3 to 20 consume exactly those in the sparse
    # multiply/carry chain. Lean's extraction of the prefix's three instructions into one record
    # takes too much memory, so the prefix is one helper per instruction.
    one = rounds[0]
    prefix = [n for n in one if n.pc is not None and n.pc < 3]
    suffix = [n for n in one if n.pc is not None and n.pc >= 3]
    check_round_split(one, prefix, suffix)
    quotient, self_sub, mask = ([n for n in prefix if n.pc == pc] for pc in range(3))
    check_prefix_split(prefix, quotient, self_sub, mask)
    quotient_program = program(
        "fromMontRoundPrefixQuotient",
        words("w0"),
        "Nat × Nat",
        "The first instruction of one checked `from_mont_round!` invocation: compute the Montgomery "
        "quotient and the subtraction carry used by the next instruction.",
        [Param(comment="low accumulator word", dest="w0", value=Arg("w0")), *quotient],
        ["w0", "c"],
        result_text="  (w0, c)",
        struct=f"{FROM_MONT_STATE_STRUCT}\n\n{FROM_MONT_PREFIX_STRUCT}",
        clear_values=False,
        lift_lets=False,
    )
    self_sub_program = program(
        "fromMontRoundPrefixSelfSub",
        words("quotient", "subCarry"),
        "Nat",
        "The second instruction of one checked `from_mont_round!` invocation: self-subtract the "
        "quotient under the first instruction's carry.",
        [
            Param(comment="Montgomery quotient", dest="w0", value=Arg("quotient")),
            Param(comment="subtraction carry", dest="c", value=Arg("subCarry")),
            *self_sub,
        ],
        ["r12"],
        result_text="  r12",
        clear_values=False,
        lift_lets=False,
    )
    mask_program = program(
        "fromMontRoundPrefixMask",
        words("selfSub"),
        "Nat",
        "The third instruction of one checked `from_mont_round!` invocation: mask the "
        "self-subtraction result to the low-word cancellation carry.",
        [Param(comment="self-subtraction result", dest="r12", value=Arg("selfSub")), *mask],
        ["r12"],
        result_text="  r12",
        clear_values=False,
        lift_lets=False,
    )
    prefix_program = program(
        "fromMontRoundPrefix",
        words("w0"),
        "FromMontRoundPrefix",
        "The first three instructions of one checked `from_mont_round!` invocation, composed from "
        "three mechanically accounted one-instruction helpers: compute the quotient and the carry "
        "that cancels the low accumulator word.",
        [
            Bind(
                comment="mechanically factored PC 0",
                dest="quotientResult",
                term=App("fromMontRoundPrefixQuotient", (Arg("w0"),)),
            ),
            Project(
                comment="quotient helper output", dest="quotient", call="quotientResult", field="1"
            ),
            Project(
                comment="quotient helper output", dest="subCarry", call="quotientResult", field="2"
            ),
            Bind(
                comment="mechanically factored PC 1",
                dest="selfSub",
                term=App("fromMontRoundPrefixSelfSub", (Reg("quotient"), Reg("subCarry"))),
            ),
            Bind(
                comment="mechanically factored PC 2",
                dest="carry",
                term=App("fromMontRoundPrefixMask", (Reg("selfSub"),)),
            ),
        ],
        ["quotient", "carry"],
        lift_lets=False,
    )
    suffix_lifter = Armv7emLifter({"r1": "in"})
    suffix_lifter.bind_memory("r1", "modulus")
    suffix_program = program(
        "fromMontRoundSuffix",
        (("modulus", "Limbs"), ("st", "FromMontState"), *words("q", "carry")),
        "FromMontState",
        "The final eighteen instructions of one checked `from_mont_round!` invocation: multiply "
        "the sparse modulus by the quotient and propagate its carry through the accumulator.",
        [
            *suffix_lifter.nodes,
            *(
                StateLoad(comment="accumulator argument", dest=f, arg="st", field=f)
                for f in fields[1:]
            ),
            Param(comment="Montgomery quotient", dest="w0", value=Arg("q")),
            Param(comment="low-word cancellation carry", dest="r12", value=Arg("carry")),
            *suffix,
        ],
        [*fields[1:], "tmp"],
        arg_fields=state,
    )
    round_program = program(
        "fromMontRound",
        (("modulus", "Limbs"), ("st", "FromMontState")),
        "FromMontState",
        "One `from_mont_round!` invocation, composed from the mechanically checked quotient prefix "
        "and sparse multiply/carry suffix. All eight invocations are required to have the same "
        "binding IR after applying their exact source register rotation.",
        [
            Bind(
                comment="mechanically factored PCs 0 through 2",
                dest="quotientResult",
                term=App("fromMontRoundPrefix", (Get(Arg("st"), "w0"),)),
            ),
            Project(
                comment="quotient prefix output", dest="q", call="quotientResult", field="quotient"
            ),
            Project(
                comment="quotient prefix output", dest="carry", call="quotientResult", field="carry"
            ),
            Bind(
                comment="mechanically factored PCs 3 through 20",
                dest="suffix",
                term=App(
                    "fromMontRoundSuffix", (Arg("modulus"), Arg("st"), Reg("q"), Reg("carry"))
                ),
            ),
            *(
                Project(comment="sparse suffix output", dest=f, call="suffix", field=f)
                for f in fields
            ),
        ],
        list(fields),
        arg_fields=state,
    )

    # The final reduction, split where the add-back mask is formed.
    final = final_nodes(flat.nodes)
    subtraction = [n for n in final if n.pc is not None and n.pc < 14]
    addback = [n for n in final if n.pc is not None and n.pc >= 14]
    check_final_split(final, subtraction, addback)
    subtraction_lifter = Armv7emLifter({"r1": "in"})
    subtraction_lifter.bind_memory("r1", "modulus")
    subtraction_program = program(
        "fromMontFinalSubtractionBlock",
        (("modulus", "Limbs"), ("st", "FromMontState")),
        "FromMontFinalSubtraction",
        "The first fourteen instructions of the checked `from_mont` final reduction: subtract "
        "the sparse modulus and turn the final no-borrow carry into an add-back mask.",
        [
            *subtraction_lifter.nodes,
            *(
                StateLoad(comment="post-round accumulator argument", dest=f, arg="st", field=f)
                for f in fields
            ),
            *subtraction,
        ],
        [*fields, "c", "r12"],
        struct=FROM_MONT_FINAL_SUBTRACTION_STRUCT,
        arg_fields=state,
    )
    sub_fields = (*fields, "carry", "mask")
    addback_lifter = Armv7emLifter({"r1": "in"})
    addback_lifter.bind_memory("r1", "modulus")
    addback_program = program(
        "fromMontFinalAddBackBlock",
        (("modulus", "Limbs"), ("sub", "FromMontFinalSubtraction")),
        "FromMontState",
        "The final seventeen instructions of the checked `from_mont` final reduction: add the "
        "sparse modulus back under the subtraction helper's borrow mask.",
        [
            *addback_lifter.nodes,
            *(
                StateLoad(comment="subtraction helper output", dest=f, arg="sub", field=f)
                for f in fields
            ),
            StateLoad(comment="subtraction borrow mask", dest="r12", arg="sub", field="mask"),
            *addback,
        ],
        list(fields),
        arg_fields={"sub": sub_fields},
    )
    final_program = program(
        "fromMontFinalReductionBlock",
        (("modulus", "Limbs"), ("st", "FromMontState")),
        "FromMontState",
        "The checked 31-instruction suffix of `from_mont`, composed from mechanically accounted "
        "subtraction-mask and masked-add-back helpers. Its ninth accumulator word is unchanged.",
        [
            Bind(
                comment="mechanically factored PCs 0 through 13",
                dest="subtraction",
                term=App("fromMontFinalSubtractionBlock", (Arg("modulus"), Arg("st"))),
            ),
            Bind(
                comment="mechanically factored PCs 14 through 30",
                dest="addback",
                term=App("fromMontFinalAddBackBlock", (Arg("modulus"), Reg("subtraction"))),
            ),
        ],
        ["addback"],
        result_text="  addback",
        arg_fields=state,
    )

    # The block: its loads, a call per round on the rotated accumulator, the final reduction, and
    # the returned words joined into limbs.
    nodes: list[Node] = [n for n in flat.nodes if n.pc is None or n.pc < FIRST_ROUND]
    for site, registers in enumerate(rotations, 1):
        call = f"round{site}"
        nodes.append(
            Bind(
                comment=f"from_mont_round!, invocation {site}",
                dest=call,
                term=App(
                    "fromMontRound", (Arg("modulus"), Tuple(tuple(Reg(r) for r in registers[:9])))
                ),
            )
        )
        nodes += [
            Project(comment=f"round {site} output", dest=r, call=call, field=f, optional=True)
            for r, f in zip(registers[1:], fields, strict=True)
        ]
    nodes.append(
        Bind(
            comment="checked final reduction, PCs 177 through 207",
            dest="finalReduction",
            term=App(
                "fromMontFinalReductionBlock",
                (Arg("modulus"), Tuple(tuple(Reg(r) for r in FROM_MONT_FINAL_REGISTERS))),
            ),
        )
    )
    nodes += [
        Project(
            comment="final reduction output", dest=r, call="finalReduction", field=f, optional=True
        )
        for r, f in zip(FROM_MONT_FINAL_REGISTERS, fields, strict=True)
    ]
    returned = rust.returned_registers(parsed, "from_mont")
    results = []
    for limb, (low, high) in enumerate(zip(returned[::2], returned[1::2], strict=True)):
        results.append(f"result{limb}")
        nodes.append(
            Join(comment="join returned words", dest=results[-1], low=Reg(low), high=Reg(high))
        )
    block = program(
        "fromMontBlock",
        (("value", "Limbs"), ("modulus", "Limbs")),
        "Limbs",
        "The fixed-register inline `asm!` block of `from_mont`: load eight input words, apply "
        "eight mechanically checked rotated Montgomery rounds, then call the checked final "
        "reduction block once.",
        nodes,
        results,
    )
    return [
        quotient_program,
        self_sub_program,
        mask_program,
        prefix_program,
        suffix_program,
        round_program,
        subtraction_program,
        addback_program,
        final_program,
        block,
    ]


