BATCH_DECLARATIONS = (
    Declaration("pflo", "inout", "pflo", "pflo"),
    Declaration("pfhi", "inout", "pfhi", "pfhi"),
    Declaration("pglo", "inout", "pglo", "pglo"),
    Declaration("pghi", "inout", "pghi", "pghi"),
    Declaration("d", "inout", "d", "d"),
    Declaration("remaining", "inout", "remaining", "_"),
    Declaration("odd", "out", "_", "_"),
    Declaration("swap", "out", "_", "_"),
    Declaration("alo", "out", "_", "_"),
    Declaration("ahi", "out", "_", "_"),
    Declaration("tmp", "out", "_", "_"),
)
CARRIED = ("pflo", "pfhi", "pglo", "pghi", "d", "remaining")
# The positions of the bindings of the round's last five instructions: the shift of packed `g`,
# the decrement with its four bindings, and the branch.
FINISH_SCHEDULE = [27, 28, 29, 30, 30, 30, 30, 31]


def composition(
    name: str,
    params: Sequence[tuple[str, str]],
    doc: str,
    bindings: Sequence[tuple[str, Term, str]],
    result_text: str,
    results: Sequence[str],
) -> Program:
    """Rust around a block, which the module writes as `(name, term, comment)` bindings; their
    bounds are the annotations'."""
    nodes = [
        Bind(comment=comment, dest=b, term=term, annotated=True) for b, term, comment in bindings
    ]
    return program(name, params, "Divstep59Result", doc, nodes, results, result_text=result_text)


def batch_programs(source: str) -> list[Program]:
    """`batch`'s loop body as one round, its last five instructions factored, iterated by the
    public count in the Rust around it."""
    inner = rust.checked_function(source, "batch", BATCH_RUST)
    instructions, origins, declarations, options = rust.parse_asm_invocation(
        source,
        inner,
        "batch",
        reserved_names={"c", "m", "s"},
        allowed_options={"pure", "nomem", "nostack"},
        required_options={"pure", "nomem", "nostack"},
    )
    if origins != (None,) * len(instructions):
        raise GenerationError("batch: macro invocations in the loop body are unsupported")
    if declarations != BATCH_DECLARATIONS:
        raise GenerationError("batch: assembly operand declarations differ from the checked loop")
    if options != {"pure", "nomem", "nostack"}:
        raise GenerationError("batch: assembly options differ from the checked loop")
    if instructions[0] != "2:" or instructions[-1] != "bne 2b":
        raise GenerationError("batch: expected one loop from label `2:` through `bne 2b`")

    lifter = Armv7emLifter({d.name: d.kind for d in declarations}, loop=True)
    for register in CARRIED:
        lifter.bind_argument(register, Get(Arg("st"), register))
    lift_all(lifter, instructions)
    if not lifter.label_seen or not lifter.branch_seen:
        raise GenerationError("batch: loop label and backward branch must both be present")

    # The last five instructions are a helper of their own: extracting the round's lets through
    # the cross-word shift otherwise makes Lean normalize the whole dependent tail recursively.
    split = next((i for i, n in enumerate(lifter.nodes) if n.pc == FINISH_SCHEDULE[0]), None)
    if split is None or [n.pc for n in lifter.nodes[split:] for _ in n.lets()] != FINISH_SCHEDULE:
        raise GenerationError("batch: final shift and loop-control schedule changed")
    finish_results = ["pglo", "pghi", "remaining", "c", "z", "branch"]
    finish = program(
        "batchRoundFinish",
        words("pglo", "pghi", "remaining"),
        "BatchRoundFinish",
        "The final five instructions of one validated `batch` loop iteration: shift packed `g`, "
        "decrement the public count, and compute the backward-branch decision.",
        [
            *(
                Param(comment=f"input {r}", dest=r, value=Arg(r))
                for r in ("pglo", "pghi", "remaining")
            ),
            *lifter.nodes[split:],
        ],
        finish_results,
        struct=BATCH_FINISH_STRUCT,
        clear_values=False,
    )
    round_ = program(
        "batchRound",
        (("st", "BatchState"),),
        "BatchState",
        "One complete iteration of the inline `asm!` loop of `batch`, including its public-count "
        "decrement, resulting flags, and backward-branch decision.",
        [
            *lifter.nodes[:split],
            Bind(
                comment="mechanically factored PCs 27 through 31",
                dest="finish",
                term=App("batchRoundFinish", (Reg("pglo"), Reg("pghi"), Reg("remaining"))),
            ),
            *(
                Project(comment="factored suffix output", dest=f, call="finish", field=f)
                for f in finish_results
            ),
        ],
        [*CARRIED, "c", "z", "branch"],
        struct=BATCH_STATE_STRUCT,
        arg_fields={"st": CARRIED},
        clear_values=False,
        # Extracting the loop's lets one instruction at a time: lifting the whole chain makes Lean
        # normalize the nested `BatchState` equality recursively before `word_step` can factor it.
        lift_lets=False,
    )
    st = Reg("st")
    block = composition(
        "batchBlock",
        words("k", "delta", "f", "g"),
        "The inline `asm!` block and surrounding Rust of `batch`: pack the low words, iterate the "
        "mechanically transcribed loop body by its public positive count `k`, sign-extend the new "
        "`two_delta`, and decode the two packed matrix rows.",
        [
            (
                "pf",
                App("orrw", (App("andw", (Arg("f"), Lit("0xfffff"))), Lit("0xfffffe0000000000"))),
                "pack the low word of f",
            ),
            (
                "pg",
                App("orrw", (App("andw", (Arg("g"), Lit("0xfffff"))), Lit("0xc000000000000000"))),
                "pack the low word of g",
            ),
            ("pflo", Infix("%", Reg("pf"), WORD_MOD), "Rust cast to the low u32"),
            ("pfhi", Infix("/", Reg("pf"), WORD_MOD), "Rust shift and cast to the high u32"),
            ("pglo", Infix("%", Reg("pg"), WORD_MOD), "Rust cast to the low u32"),
            ("pghi", Infix("/", Reg("pg"), WORD_MOD), "Rust shift and cast to the high u32"),
            ("d", Infix("%", Arg("delta"), WORD_MOD), "Rust cast of two_delta to u32"),
            (
                "st",
                Ascribe(
                    Tuple(
                        (
                            *(Reg(r) for r in ("pflo", "pfhi", "pglo", "pghi", "d")),
                            Arg("k"),
                            Lit("0"),
                            Lit("0"),
                            Lit("0"),
                        )
                    ),
                    "BatchState",
                ),
                "initial assembly registers and flags",
            ),
            ("st", App("batchRound^[k]", (st,)), "public-count assembly loop"),
            (
                "pf",
                App("join32", (Get(st, "pflo"), Get(st, "pfhi"))),
                "join the returned packed f words",
            ),
            (
                "pg",
                App("join32", (Get(st, "pglo"), Get(st, "pghi"))),
                "join the returned packed g words",
            ),
            ("delta", App("signExtend32", (Get(st, "d"),)), "sign-extend the returned u32"),
            ("uv", App("unpackWords", (Arg("k"), Reg("pf"))), "Rust unpack(k, pf)"),
            ("qr", App("unpackWords", (Arg("k"), Reg("pg"))), "Rust unpack(k, pg)"),
        ],
        "  ⟨delta, uv.1, uv.2, qr.1, qr.2⟩",
        ["delta", "uv", "qr"],
    )
    return [finish, round_, block]


def divstep59_program(source: str) -> Program:
    """The Rust `divstep59`: three batches, the next low words between them, and the product of
    their matrices."""
    rust.checked_function(source, "divstep59", DIVSTEP59_RUST)
    bindings: list[tuple[str, Term, str]] = []
    previous: tuple[Term, Term] = (Arg("f0"), Arg("g0"))
    delta: Term = Arg("two_delta")
    ordinals = ("first", "second")
    for index, steps in enumerate((20, 20)):
        n = index + 1
        f, g = previous
        b = f"b{n}"
        bindings.append(
            (
                b,
                App("batchBlock", (Lit(str(steps)), delta, f, g)),
                f"batch({steps}, {_rust(delta)}, {_rust(f)}, {_rust(g)})",
            )
        )
        for name, field in (("d", "two_delta"), ("u", "u"), ("v", "v"), ("q", "q"), ("r", "r")):
            bindings.append((f"{name}{n}", Get(Reg(b), field), f"{ordinals[index]} batch output"))
        u, v, q, r = (Reg(f"{name}{n}") for name in "uvqr")
        which = ("one", "two")[index]
        bindings.append(
            (
                f"f{n}",
                App("nextLowWords", (Lit("20"), u, v, f, g)),
                f"next_low for f after batch {which}",
            )
        )
        bindings.append(
            (
                f"g{n}",
                App("nextLowWords", (Lit("20"), q, r, f, g)),
                f"next_low for g after batch {which}",
            )
        )
        previous, delta = (Reg(f"f{n}"), Reg(f"g{n}")), Reg(f"d{n}")
    bindings.append(
        ("b3", App("batchBlock", (Lit("19"), delta, *previous)), "batch(19, d2, f2, g2)")
    )
    bindings.append(
        (
            "m21",
            App(
                "matMulWords",
                (
                    Prod(tuple(Reg(f"{x}2") for x in "uvqr")),
                    Prod(tuple(Reg(f"{x}1") for x in "uvqr")),
                ),
            ),
            "inner Rust mat_mul",
        )
    )
    bindings.append(
        (
            "matrix",
            App("matMulWords", (Prod(tuple(Get(Reg("b3"), x) for x in "uvqr")), Reg("m21"))),
            "outer Rust mat_mul",
        )
    )
    return composition(
        "divstep59Block",
        words("two_delta", "f0", "g0"),
        "The Rust `divstep59` composition: packed batches of 20, 20, and 19 divsteps, with the "
        "next low words between them and the newest transition matrix multiplied on the left.",
        bindings,
        "  ⟨b3.two_delta, matrix.1, matrix.2.1, matrix.2.2.1, matrix.2.2.2⟩",
        ["b3", "matrix"],
    )


def _rust(term: Term) -> str:
    """The Rust name of a word in the comments of `divstep59`'s bindings."""
    assert isinstance(term, (Reg, Arg))
    return term.name


# -- the transcription -------------------------------------------------------------------------


def programs(source: str | None = None) -> list[Program]:
    """Every definition of the transcription, in order."""
    source = SOURCE.read_text() if source is None else source
    rust.check_asm_inventory(source, ASM_BLOCKS, TARGET.isa.name)
    *primitives, cond_sub = [primitive(source, block) for block in PRIMITIVES]
    return [
        *primitives,
        *from_mont_programs(source),
        *batch_programs(source),
        divstep59_program(source),
        cond_sub,
    ]


def text(source: str | None = None) -> str:
    return HEADER + "\n".join(definition(p, COLUMN) for p in programs(source)) + FOOTER
