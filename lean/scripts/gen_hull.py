#!/usr/bin/env python3
"""Generate `lean/PastaCurves/Inversion/HullData.lean` from `hull_certificate.json`.

The JSON is the termination certificate for the half-delta divstep (Bernstein's "hull light" data of
2023, public domain, from which his Sage script generates the HOL Light proof
`Divstep/hull_light.ml`): the half-planes of the two stable hulls `H0` and `H1`, of the outer box
and the initial triangle, and one Farkas record per target half-plane for each of the ten
inclusions. `verify_hull_certificate.py` checks the JSON independently in exact arithmetic;
`PastaCurves/Inversion/HullCert.lean` proves the same facts from the generated definitions by
`decide`.

    gen_hull.py            write the Lean file
    gen_hull.py --check    exit 1 if the Lean file is not what the JSON generates
"""

import json
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON = ROOT / "scripts" / "hull_certificate.json"
OUT = ROOT / "PastaCurves" / "Inversion" / "HullData.lean"

HEADER = """\
import PastaCurves.Inversion.HullBound

/-!
# The hull certificate's data

GENERATED by `lean/scripts/gen_hull.py` from `lean/scripts/hull_certificate.json`; do not edit.

The data is Bernstein's "hull light" certificate of 2023: `hull-light-20230416.sage` at `cr.yp.to`,
public domain, SHA-256 `{sha}`. Run in
Sage, it generates the HOL Light proof `Divstep/hull_light.ml` of `jrh13/hol-light`,
<https://github.com/jrh13/hol-light/tree/6f6ac17e8f4bff6c7f6897de0570a004744e4963/Divstep>, where
Harrison's files connect it to the definition of `divstep`. It consists of half-planes
`a x + b y ≤ c` for four regions: the stable hulls `H0` and `H1`, the outer box `houter`, and the
initial triangle `hinit`. A half-plane `⟨a, b, c⟩` of `H0` or `H1` is the edge through two
consecutive vertices of the script's polygon (vertices with power-of-two denominators, at most
`2^16`), scaled by `2^32` to integers and divided by the gcd of the three. For each of the ten
inclusions it gives one Farkas record `⟨i, j, m, n, p, q⟩` per target half-plane, in the target's
order: `m` times source half-plane `i` plus `n` times source half-plane `j` equals `q` times the
target half-plane pulled back through the map, in the coefficients of `x` and `y`, and falls short
of it by the slack `p` in the constant. Each map of a divstep inclusion (all but `init2stable` and
`theoremouter`) is also given as the product of the script's divstep matrices `U0`, `U1`, and `D`
(the step at even `g`, at odd `g` without a swap, and at odd `g` with a swap), the rightmost factor
acting first. `HullCert.lean` turns these into `Certified H0 H1`.
-/

namespace PastaCurves.Inversion.Hull

"""

# The width of the generated prose, as the hand-written modules wrap theirs.
WIDTH = 100


def words(text):
    """The words of `text`, each code span kept whole, so that filling never breaks one."""
    out, word, code = [], "", False
    for ch in text:
        if ch == "`":
            code = not code
        if ch == " " and not code:
            if word:
                out.append(word)
            word = ""
        else:
            word += ch
    if word:
        out.append(word)
    return out


def fill(text):
    """`text` filled greedily to `WIDTH` columns."""
    lines = [""]
    for word in words(text):
        if lines[-1] and len(lines[-1]) + 1 + len(word) > WIDTH:
            lines.append(word)
        else:
            lines[-1] = f"{lines[-1]} {word}" if lines[-1] else word
    return "\n".join(lines)


def rat(text):
    """A JSON rational, as a Lean `ℚ` literal."""
    q = Fraction(text)
    if q.denominator == 1:
        n = q.numerator
        return f"({n} : ℚ)" if n < 0 else str(n)
    return f"({q.numerator} / {q.denominator} : ℚ)"


def region(name, doc, planes):
    lines = [f"/-- {doc} -/", f"def {name} : Region := ["]
    for a, b, c in planes:
        lines.append(f"  ⟨{rat(a)}, {rat(b)}, {rat(c)}⟩,")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("]")
    return "\n".join(lines) + "\n\n"


# The divstep matrices of the hull-light script, acting on column vectors `(x, y)`.
U0 = ((Fraction(1), Fraction(0)), (Fraction(0), Fraction(1, 2)))
U1 = ((Fraction(1), Fraction(0)), (Fraction(1, 2), Fraction(1, 2)))
D = ((Fraction(0), Fraction(1)), (Fraction(-1, 2), Fraction(1, 2)))


def mul(*ms):
    """The matrix product, the rightmost factor acting first."""
    r = ((Fraction(1), Fraction(0)), (Fraction(0), Fraction(1)))
    for m in ms:
        r = tuple(
            tuple(sum(r[i][k] * m[k][j] for k in range(2)) for j in range(2)) for i in range(2)
        )
    return r


def inverse(m):
    det = m[0][0] * m[1][1] - m[0][1] * m[1][0]
    return ((m[1][1] / det, -m[0][1] / det), (-m[1][0] / det, m[0][0] / det))


def scale(c, m):
    return tuple(tuple(c * x for x in row) for row in m)


# Each inclusion's map as the script writes it (`hull-light-20230416.sage`, the `prove_inclusion`
# calls), checked against the JSON matrix by `generate`.
STEPS = {
    "theorem0": ("`U0`", U0),
    "theorem1": ("`U1`", U1),
    "theorem3": ("`D`", D),
    "theorem5": ("`D · U0`", mul(D, U0)),
    "theorem_2": ("`U0 · D · U0 · U0`", mul(U0, D, U0, U0)),
    "theorem_1": ("`U1 · D · U0 · U0`", mul(U1, D, U0, U0)),
    "theorem_4scale": (
        "`(33/32) (D · U0 · U0)⁻¹ · U0 · D · U0 · U0 · U0`",
        scale(Fraction(33, 32), mul(inverse(mul(D, U0, U0)), U0, D, U0, U0, U0)),
    ),
    "theorem_3scale": (
        "`(33/32) (D · U0 · U0)⁻¹ · U1 · D · U0 · U0 · U0`",
        scale(Fraction(33, 32), mul(inverse(mul(D, U0, U0)), U1, D, U0, U0, U0)),
    ),
}


def farkas(inc):
    steps = STEPS.get(inc["name"])
    via = f" ({steps[0]})" if steps else ""
    lines = [
        fill(
            f"/-- Farkas records for `{inc['name']}`: `{inc['source']}` into `{inc['target']}` under "
            f"the map `{inc['matrix']}`{via}, divided by `s^{inc['k']}`. -/"
        ),
        f"def farkas_{inc['name']} : List Farkas := [",
    ]
    for r in inc["farkas"]:
        lines.append(
            f"  ⟨{r['i']}, {r['j']}, {rat(r['m'])}, {rat(r['n'])}, {rat(r['p'])}, {rat(r['q'])}⟩,"
        )
    lines[-1] = lines[-1].rstrip(",")
    lines.append("]")
    return "\n".join(lines) + "\n\n"


def box_bounds(planes):
    """The bounds of the axis-aligned box given by its four half-planes."""
    xmax = next(
        Fraction(c) / Fraction(a) for a, b, c in planes if Fraction(b) == 0 and Fraction(a) > 0
    )
    ymax = next(
        Fraction(c) / Fraction(b) for a, b, c in planes if Fraction(a) == 0 and Fraction(b) > 0
    )
    return xmax, ymax


def generate(cert):
    for inc in cert["inclusions"]:
        if inc["name"] in STEPS:
            want = tuple(tuple(Fraction(x) for x in row) for row in inc["matrix"])
            if STEPS[inc["name"]][1] != want:
                raise SystemExit(
                    f"{inc['name']}: the divstep product does not give the JSON matrix"
                )
    out = HEADER.format(sha=cert["source"]["sha256"])
    polys = cert["polygons"]
    n0, n1 = len(polys["H0"]), len(polys["H1"])
    xmax, ymax = box_bounds(polys["houter"])
    out += region("H0", f"The stable hull `S_{{-1/2}}`, {n0} half-planes.", polys["H0"])
    out += region("H1", f"The stable hull `S_{{1/2}}`, {n1} half-planes.", polys["H1"])
    out += region("houter", f"The outer box `|x| ≤ {xmax}`, `|y| ≤ {ymax}`.", polys["houter"])
    out += region("hinit", "The initial triangle `0 ≤ y ≤ x ≤ 1`.", polys["hinit"])
    for inc in cert["inclusions"]:
        out += farkas(inc)
    out += "end PastaCurves.Inversion.Hull\n"
    return out


def main(argv):
    cert = json.loads(JSON.read_text())
    text = generate(cert)
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(
                f"{OUT.relative_to(ROOT)} is not current; run lean/scripts/gen_hull.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.relative_to(ROOT)}: current.")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
