//! This module contains implementations for the Pallas and Vesta elliptic curve
//! groups, and for the isogenous curves used to hash to them.
//!
//! # The curves
//!
//! Pallas is the curve $y^2 = x^3 + 5$ over $\mathbb{F}_p$, and Vesta the same
//! equation over $\mathbb{F}_q$, where $p$ and $q$ are the Pasta primes: the order
//! of each curve's group is the other's base field. A point of the curve is a zero
//! of $f(x, y) = y^2 - x^3 - 5$ with coordinates in the base field, together with
//! one point at infinity $O$, the identity, which no zero of $f$ represents. The
//! curves `IsoEp` and `IsoEq`, used for hashing, are $y^2 = x^3 + a x + b$ with
//! $a \neq 0$, and map to Pallas and Vesta by 3-isogenies.
//!
//! # Models
//!
//! The crate represents points in three models of the same curve. The affine chart
//! misses $O$; the two others complete it in a projective space, where a point is
//! a class of nonzero triples under a scaling with weights $(w_X, w_Y, w_Z)$:
//! $(X : Y : Z) = (\lambda^{w_X} X : \lambda^{w_Y} Y : \lambda^{w_Z} Z)$ for every
//! nonzero $\lambda$. The equation must be homogeneous for the weights so that its
//! zeros are classes, and the affine coordinates are the quotients of weight zero.
//!
//! | Model      | Type                       | Weights     | Equation                        | Affine point         | Identity                                           |
//! | ---------- | -------------------------- | ----------- | ------------------------------- | -------------------- | -------------------------------------------------- |
//! | Affine     | [`EpAffine`], `affine.rs`  | none        | $y^2 = x^3 + a x + b$           | $(x, y)$             | stored as $(0, 0)$, not on the curve as $b \neq 0$ |
//! | Jacobian   | [`Ep`], `jacobian.rs`      | $(2, 3, 1)$ | $Y^2 = X^3 + a X Z^4 + b Z^6$   | $(X / Z^2, Y / Z^3)$ | any $Z = 0$, stored as $(0, 0, 0)$                 |
//! | Projective | [`projective::Projective`] | $(1, 1, 1)$ | $Y^2 Z = X^3 + a X Z^2 + b Z^3$ | $(X / Z, Y / Z)$     | $(0 : 1 : 0)$                                      |
//!
//! The public point types are the affine and Jacobian ones. The projective model is
//! crate-private, with $b = 5$ only: it has complete formulas on Pallas and Vesta,
//! which the constant-time scalar multiplication in [`projective::mul`] uses.
//!
//! # Why the weights are $(2, 3, 1)$
//!
//! Let $L(nO)$ be the functions on the curve whose only pole is at $O$, of order at
//! most $n$. By the Riemann-Roch theorem it has dimension $n$ for $n \geq 1$, with
//! $L(2O) = \langle 1, x \rangle$ and $L(3O) = \langle 1, x, y \rangle$: $x$ has a
//! pole of order 2 at $O$ and $y$ one of order 3 (Silverman, *The Arithmetic of
//! Elliptic Curves*, III.3). The graded ring $\bigoplus_n L(nO)$ is generated by
//! $Z$ (the constant 1, in degree 1), $X$ (degree 2) and $Y$ (degree 3), with one
//! relation in degree 6, the Jacobian equation: the weights are the pole orders.
//! Keeping only the degrees divisible by 3 gives a ring generated by
//! $L(3O) = \langle 1, x, y \rangle$ in degree 1, whose equation is the cubic of the
//! projective plane. Both rings describe the same curve.
//!
//! # Maps between the models
//!
//! In `maps.rs`, and in `iso.rs` for the isogenies from the curves used for
//! hashing:
//!
//! - Jacobian to projective: $(X : Y : Z) \mapsto (X Z : Y : Z^3)$, the three
//!   monomials of weighted degree 3. It is defined at $O$, which it sends to
//!   $(0 : 1 : 0)$; the code also maps the stored $(0, 0, 0)$ there.
//! - Projective to Jacobian: $(X : Y : Z) \mapsto (X Z : Y Z^2 : Z)$. It sends $O$
//!   to $(0, 0, 0)$, not a point but the crate's stored identity.
//! - Jacobian to affine: $(X / Z^2, Y / Z^3)$, one inversion per point, or one for
//!   many points in [`group::Curve::batch_normalize`].
//! - Affine to Jacobian and to projective: $(x, y) \mapsto (x : y : 1)$.
//! - The 3-isogenies from `IsoEp` and `IsoEq` to Pallas and Vesta, given by
//!   [`Ep::ISOGENY_CONSTANTS`] and [`Eq::ISOGENY_CONSTANTS`].
//!
//! The projective model also has the 3-isogeny $\psi_b$ from $E_b$ to $E_{-27b}$
//! and the isomorphism from $E_{729b}$ back to $E_b$, whose composition with a
//! second $\psi$ is the tripling of [`projective::Projective`].

